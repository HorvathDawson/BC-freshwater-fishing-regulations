#!/bin/bash
# (T313) STAGING ONLY: build the app for the iOS SIMULATOR (Release, JS bundled, no Metro) reading STAGING data, the
# environment switch on. No Apple account, no signing (CODE_SIGNING_ALLOWED=NO): a simulator .app only, never a device
# or App Store build. HEAVY: wrapped in scripts/heavy.sh (waits for the machine lock).
# Builds COMMITTED HEAD only, like build-apk.sh: a temporary git worktree at HEAD (other lanes' uncommitted edits never
# enter the build), removed on exit by a trap. node_modules via `pnpm install --offline --frozen-lockfile` (applies
# app/patches, incl. the MapLibre iOS half from T217); the gitignored ios/ is regenerated by `expo prebuild` there; pods.
# Output: app/dist/ios-sim/canifishthis.app (+ canifishthis-staging-<version>-<sha>.app.zip, build.log).
#   Install:  xcrun simctl install <udid> app/dist/ios-sim/canifishthis.app   (app/tools/testbed/session-ios.sh does it)
# Usage: deploy/staging/build-ios-sim.sh [--testbed | --probes] [--dry-run]
#   --testbed  also the test-bed flags of session.sh (update channel `test`, pan probe, test reports)
set -euo pipefail
cd "$(dirname "$0")/../.."
REPO=$PWD
if [[ " $* " == *" --dry-run "* ]]; then DRY=1; else DRY=; fi
if [[ -z ${BUILD_IOS_INNER:-} && -z $DRY ]]; then
  export BUILD_IOS_INNER=1
  exec scripts/heavy.sh build-ios-sim 20 -- "$0" "$@"
fi
export EXPO_PUBLIC_APP_ENV=staging EXPO_PUBLIC_ENV_SWITCH=1 EXPO_PUBLIC_CONTACT=${EXPO_PUBLIC_CONTACT:-support@canifishthis.ca}
# (T313) --probes: the test bed's measuring switches only ([pan] [open] [stall] [target] in the log), on the live channel
if [[ " $* " == *" --probes "* ]]; then export EXPO_PUBLIC_PAN_PROBE=1; fi
if [[ " $* " == *" --testbed "* ]]; then
  export EXPO_PUBLIC_UPDATE_CHANNEL=test EXPO_PUBLIC_PAN_PROBE=1 EXPO_PUBLIC_TEST_REPORTS=1
fi
M=app/apps/mobile
SHA_FULL=$(git rev-parse HEAD)
echo "building committed HEAD $SHA_FULL for the iOS Simulator (uncommitted working-tree edits are NOT included)"
WT=${TMPDIR:-/tmp}/build-ios-wt-$$
OUT=$REPO/app/dist/ios-sim
if [[ -n $DRY ]]; then
  echo "[dry-run] git worktree add --detach $WT $SHA_FULL"
  echo "[dry-run] (cd \$WT/app && pnpm install --offline --frozen-lockfile)"
  echo "[dry-run] (cd \$WT/$M && npx expo prebuild --platform ios --no-install); (cd ios && pod install)"
  echo "[dry-run] xcodebuild -workspace ios/<Name>.xcworkspace -scheme <Name> -configuration Release -sdk iphonesimulator ARCHS=arm64 CODE_SIGNING_ALLOWED=NO"
  echo "[dry-run] copy <Name>.app as canifishthis.app -> $OUT/"
  exit 0
fi
cleanup() { cd "$REPO" && git worktree remove --force "$WT" 2>/dev/null || rm -rf "$WT"; git worktree prune; }
trap cleanup EXIT
git worktree add --detach "$WT" "$SHA_FULL"
cd "$WT"
VER=$(node -p "require('./$M/app.json').expo.version")
SHA=$(git rev-parse --short HEAD)
export EXPO_PUBLIC_GIT_SHA=$SHA_FULL
mkdir -p "$OUT"
LOG=$OUT/build.log; : > "$LOG"
(cd app && pnpm install --offline --frozen-lockfile)
cd "$M"
npx expo prebuild --platform ios --no-install
# the bundle phase runs node from .xcode.env(.local); prebuild writes .xcode.env only
echo "export NODE_BINARY=$(command -v node)" > ios/.xcode.env.local
(cd ios && LANG=en_US.UTF-8 pod install) 2>&1 | tee -a "$LOG" | tail -5
t0=$(date +%s)
DD=$WT/$M/ios/build-dd
# no -destination: CoreSimulator need not answer (an Xcode whose first launch is pending hangs in simctl)
# the project is named from expo.name ("Can I Fish?" → CanIFish), not the slug: found, never assumed
WS=$(ls -d ios/*.xcworkspace | head -1); SCHEME=$(basename "$WS" .xcworkspace)
xcodebuild -workspace "$WS" -scheme "$SCHEME" -configuration Release \
  -sdk iphonesimulator -derivedDataPath "$DD" -jobs 4 \
  ARCHS=arm64 ONLY_ACTIVE_ARCH=YES CODE_SIGNING_ALLOWED=NO CODE_SIGNING_REQUIRED=NO build >>"$LOG" 2>&1 \
  || { echo "xcodebuild failed ($LOG):" >&2; grep -E "error:|BUILD FAILED" "$LOG" | head -30 >&2; exit 1; }
APP=$(ls -d "$DD"/Build/Products/Release-iphonesimulator/*.app | head -1)
[[ -d $APP ]] || { echo "no $APP" >&2; exit 1; }
rm -rf "$OUT/canifishthis.app"; cp -R "$APP" "$OUT/canifishthis.app"
NAME="canifishthis-staging-$VER-$SHA.app.zip"
(cd "$OUT" && rm -f canifishthis-staging-*.app.zip && ditto -c -k --keepParent canifishthis.app "$NAME")
echo "$SHA_FULL" > "$OUT/sha"
echo "built $OUT/canifishthis.app ($NAME) in $(( $(date +%s) - t0 )) s"
