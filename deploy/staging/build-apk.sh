#!/bin/bash
# STAGING ONLY: build a release arm64 APK of the app reading STAGING data (T232 env, switch on, T251 version stamp) and
# publish it to bc-fishing-regulations-staging under app/android/ (served by the staging data worker):
#   https://data-staging.canifishthis.ca/app/android/index.html   (link, version, date, size, install steps)
#   .../app/android/latest.apk  and  canifishthis-staging-<version>-<sha>.apk
# Signed with Expo's debug keystore (android/app/debug.keystore, gitignored; same key every build, so an update installs
# over the previous one). Sideload only. HEAVY: wrapped in scripts/heavy.sh (waits for the machine lock).
# After upload it emails the owner the link (POST /notify/apk on the staging feeds worker, RUN_TOKEN from
# app/workers/feeds/.run-token) unless --no-email; a failed email only warns.
# Builds COMMITTED HEAD only: a temporary git worktree at HEAD (other lanes' uncommitted edits never enter the APK), removed
# on exit/failure by a trap. Prints the sha it builds. node_modules via `pnpm install --offline --frozen-lockfile` in the
# worktree; the gitignored android/ is regenerated by `expo prebuild` there, then the repo's debug.keystore (same signing
# key, so updates install over) and the SDK local.properties are copied in.
# Usage: deploy/staging/build-apk.sh [--play] [--no-upload] [--no-email] [--dry-run] [--precheck] [--publish-only]
#          [--no-fast-fail=<reason>] [--no-ci-check=<reason>] [--no-notes=<reason>] [--same-version=<reason>]
#          [--uncommitted=<reason>] [--stock-maplibre=<reason>]   (--dry-run prints the steps, builds nothing)
# (T538) THE PRECHECK, before the heavy lock (all of it, failures listed together; `--precheck` runs only it and stops):
# app.json's version has a changelog entry with a bullet and it is the newest (`scripts/check-changelog.mjs`;
# `--no-notes=<reason>`); `--play`: that version is not the one Play builds already read (play.json; `--same-version=
# <reason>`); the signing keystore(s) and certificate; `--play` uploading: the Play service account + one Play call;
# uploading: the Cloudflare (wrangler) login; emailing: the run token; the patched MapLibre AAR (exactly one) and
# llvm-readelf to prove it; `--play`: app.json clean; uncommitted app/ paths (a build is a clean worktree of HEAD: they
# are LEFT OUT) refuse unless `--uncommitted=<reason>`. Then CI (T533) and fast-fail, then the lock.
# (T538) `--play --publish-only`: redo only play.json + the email for the build already uploaded (app/dist/aab/play.json),
# e.g. after an expired Cloudflare login stopped it after the Play upload.
#
# (T267) --play: Google Play INTERNAL TESTING instead of the sideload page. Bumps android.versionCode (= ios.buildNumber)
# in app.json past max(app.json, ~/.canifishthis/play-last-version-code, the highest code Play holds) and commits ONLY
# app.json (refuses when app.json has uncommitted edits), then builds that HEAD as an AAB (bundleRelease) signed with the
# UPLOAD key named by ~/.canifishthis/upload-keystore.properties (plugins/with-upload-signing.js; the build refuses an AAB
# not signed by upload_certificate.pem), and uploads it to the internal track (deploy/staging/play-upload.py, service
# account ~/.canifishthis/play-service-account.json) with release notes = this version's changelog bullets (T538; were
# commit subjects), then emails the owner the tester link (~/.canifishthis/play-test-url, else the store page), the same
# bullets and the libmaplibre.so build id. (T538) The versionCode bump is made in the build's worktree and committed
# (app.json only) only after the AAB passed its signature and MapLibre checks — a failed build leaves no bump commit. --no-upload keeps the AAB at
# app/dist/aab/ (the FIRST upload must be done by hand in Play Console). Without --play nothing here changes: the APK is
# still debug-signed for sideloading.
#
# (T234 v1.1) A RELEASE ADDS ITS CHANGELOG ENTRY FIRST: app/packages/core/src/changelog.ts (the one changelog: 3–5 plain
# bullets for anglers, never commit subjects), for app.json's version. This script copies that version's bullets into the
# VERSION FILE our server publishes for the build's channel, which the app reads to tell a reader a newer version is out
# and to show "What's new in <version>" before it is installed:
#   sideload  app/android/latest.json  {version, build, sha, date, notes}  (beside the APK page, as before + notes)
#   --play    app/android/play.json    {version, build, sha, date, notes}  (after the Play upload; the Play build reads it)
# (T538) A version with no entry is REFUSED before the lock (`--no-notes=<reason>` goes on; the app then says "No notes
# were published for version …").
#
# (T404) --play --production: the PRODUCTION build for Google Play (closed testing, then production): EXPO_PUBLIC_APP_ENV=
# production (data.canifishthis.ca, reports to bc-fishing-feeds), no environment switch, no map lab; play.json goes to
# the PRODUCTION bucket (bc-fishing-regulations/app/android/play.json — the file a production build reads), the email
# through the production feeds worker (token app/workers/feeds/.run-token.prod). The track is PLAY_TRACK (default
# internal; the owner promotes the same build to Closed testing in Play Console, T371). THE OWNER RUNS IT:
#   CONFIRM_PROD=canifishthis.ca deploy/prod/build-apk.sh        (= this script with --play --production)
# --dry-run prints the plan and touches nothing (no build, no Play, no R2), so it needs no confirmation.
set -euo pipefail
cd "$(dirname "$0")/../.."
REPO=$PWD
if [[ " $* " == *" --dry-run "* ]]; then DRY=1; else DRY=; fi
if [[ " $* " == *" --play "* ]]; then PLAY=1; else PLAY=; fi
if [[ " $* " == *" --no-upload "* ]]; then NOUP=1; else NOUP=; fi
if [[ " $* " == *" --production "* ]]; then PROD=1; else PROD=; fi
if [[ -n $PROD ]]; then
  [[ -n $PLAY ]] || { echo "build-apk: --production is a Play build only (--play --production)" >&2; exit 2; }
  [[ -n $DRY || "${CONFIRM_PROD:-}" == canifishthis.ca ]] || {
    echo "build-apk --production: set CONFIRM_PROD=canifishthis.ca to build and publish production" >&2; exit 2; }
fi
SECRETS=$HOME/.canifishthis
PKG=ca.canifishthis.app
PLAY_STORE_URL="https://play.google.com/store/apps/details?id=$PKG"
# (T483, AGENTS 20a) FAST-FAIL FIRST: the cheap checks (typecheck, colours, answers, ledger, …) before the heavy lock and
# the long Gradle build. `--no-fast-fail=<reason>` skips them and prints the reason; a bare --no-fast-fail is refused.
NOFF=
# (T512) A PLAY INTERNAL BUILD CARRIES THE PATCHED MAPLIBRE (T420's lean feature-state patch). versionCode 19 had it;
# 20 and 21 were built without MLN_LOCAL_MAVEN and shipped the stock SDK (libmaplibre build id aab47813 instead of
# 7bf3dc29) — silently, under notes saying the map "stays smooth the longer you use it"; the owner's Pixel trace showed the
# stock per-frame feature-state cost back (~6 fps). So `--play` (not `--production`: app.config.js refuses the local SDK
# there) needs MLN_LOCAL_MAVEN (the lean repo is kept at cache/maplibre/fslean-m2; app/tools/maplibre-patch/build.sh
# makes it) or `--stock-maplibre=<reason>`, and the AAB's arm64 libmaplibre.so must carry the local AAR's build id.
STOCK_MLN=
MLN_AAR=
for a in "$@"; do
  case $a in
    --stock-maplibre) echo "build-apk: --stock-maplibre needs a reason: --stock-maplibre=\"<why the stock SDK ships>\"" >&2; exit 2 ;;
    --stock-maplibre=*) STOCK_MLN=${a#--stock-maplibre=}
      [[ -n ${STOCK_MLN// /} ]] || { echo "build-apk: --stock-maplibre= needs a reason" >&2; exit 2; } ;;
  esac
done
# (owner 2026-11-09) EVERY non-production build carries the patched MapLibre until the fix is in a MapLibre release — the
# staging-page APK too, not only --play: MLN_LOCAL_MAVEN defaults to the kept lean repo
if [[ -z $PROD && -z $STOCK_MLN && -z ${MLN_LOCAL_MAVEN:-} ]]; then export MLN_LOCAL_MAVEN="$REPO/cache/maplibre/fslean-m2"; fi
if [[ -z $PROD ]]; then
  if [[ -n $STOCK_MLN ]]; then
    [[ -z ${MLN_LOCAL_MAVEN:-} ]] || { echo "build-apk: --stock-maplibre with MLN_LOCAL_MAVEN set: pick one" >&2; exit 2; }
    echo "build-apk: STOCK MapLibre (--stock-maplibre): $STOCK_MLN"
  else
    [[ -n ${MLN_LOCAL_MAVEN:-} ]] || { echo "build-apk: every non-production build carries the patched MapLibre (T420, T512): set" \
      "MLN_LOCAL_MAVEN=$REPO/cache/maplibre/fslean-m2 (made by app/tools/maplibre-patch/build.sh with the lean patch)," \
      "or say why not with --stock-maplibre=\"<reason>\"" >&2; exit 2; }
    MLN_AAR=$(find "$MLN_LOCAL_MAVEN" -name 'android-sdk-vulkan-*.aar' 2>/dev/null)
    [[ -n $MLN_AAR && $(echo "$MLN_AAR" | wc -l) -eq 1 ]] || {
      echo "build-apk: MLN_LOCAL_MAVEN=$MLN_LOCAL_MAVEN must hold exactly one android-sdk-vulkan AAR (found: ${MLN_AAR:-none})" >&2; exit 2; }
    echo "build-apk: patched MapLibre from $MLN_AAR"
  fi
fi
NOCI=; NONOTES=; SAMEVER=; UNCOMMITTED=; PRECHECK_ONLY=; PUBLISH_ONLY=
for a in "$@"; do
  case $a in
    --precheck) PRECHECK_ONLY=1 ;;
    --publish-only) PUBLISH_ONLY=1 ;;
    --no-notes|--same-version|--uncommitted) echo "build-apk: $a needs a reason: $a=\"<why>\"" >&2; exit 2 ;;
    --no-notes=*) NONOTES=${a#--no-notes=}; [[ -n ${NONOTES// /} ]] || { echo "build-apk: --no-notes= needs a reason" >&2; exit 2; } ;;
    --same-version=*) SAMEVER=${a#--same-version=}; [[ -n ${SAMEVER// /} ]] || { echo "build-apk: --same-version= needs a reason" >&2; exit 2; } ;;
    --uncommitted=*) UNCOMMITTED=${a#--uncommitted=}; [[ -n ${UNCOMMITTED// /} ]] || { echo "build-apk: --uncommitted= needs a reason" >&2; exit 2; } ;;
    --no-ci-check) echo "build-apk: --no-ci-check needs a reason: --no-ci-check=\"<why CI is not asked>\"" >&2; exit 2 ;;
    --no-ci-check=*) NOCI=${a#--no-ci-check=}
      [[ -n ${NOCI// /} ]] || { echo "build-apk: --no-ci-check= needs a reason" >&2; exit 2; } ;;
    --no-fast-fail) echo "build-apk: --no-fast-fail needs a reason: --no-fast-fail=\"<why the cheap checks are skipped>\"" >&2; exit 2 ;;
    --no-fast-fail=*) NOFF=${a#--no-fast-fail=}
      [[ -n ${NOFF// /} ]] || { echo "build-apk: --no-fast-fail= needs a reason" >&2; exit 2; } ;;
  esac
done
BUCKET=bc-fishing-regulations-staging            # staging's; production's only with --production (CONFIRM_PROD above)
BASE=https://data-staging.canifishthis.ca/app/android
FEEDS=https://bc-fishing-feeds-staging.horvath-dawson.workers.dev; TOKF=app/workers/feeds/.run-token
NOTES_HEAD="Staging build"; ENVWORD=staging
if [[ -n $PROD ]]; then
  BUCKET=bc-fishing-regulations; BASE=https://data.canifishthis.ca/app/android
  FEEDS=https://feeds.canifishthis.ca; TOKF=app/workers/feeds/.run-token.prod
  NOTES_HEAD="Build"; ENVWORD=production
fi
TRACK=${PLAY_TRACK:-internal}
export JAVA_HOME=${JAVA_HOME:-"/Applications/Android Studio.app/Contents/jbr/Contents/Home"}
export ANDROID_HOME=${ANDROID_HOME:-$HOME/Library/Android/sdk}
M=app/apps/mobile
EMAIL=1; [[ " $* " == *" --no-email "* ]] && EMAIL=
# (T538) ONE build-id function for both paths: the GNU build id of an arm64 libmaplibre.so inside an archive
READELF=$(ls -d "$ANDROID_HOME"/ndk/*/toolchains/llvm/prebuilt/darwin-x86_64/bin/llvm-readelf 2>/dev/null | tail -1 || true)   # none: the precheck says so
mln_id() { local d; d=$(mktemp -d); unzip -q -o "$1" "$2" -d "$d" && "$READELF" -n "$d/$2" | awk '/Build ID/ {print $3}'; rm -rf "$d"; }
# mln_check <apk|aab> <path of libmaplibre.so inside>: MLN_GOT / MLN_WHAT; refuses (1) when the patched AAR is asked for
# (MLN_AAR) and the archive carries another build id — the stock SDK slipping in (T512: Play builds 20, 21)
mln_check() {
  MLN_GOT=$(mln_id "$1" "$2")
  if [[ -n $MLN_AAR ]]; then
    MLN_WANT=$(mln_id "$MLN_AAR" jni/arm64-v8a/libmaplibre.so)
    [[ -n $MLN_WANT && $MLN_GOT == "$MLN_WANT" ]] || {
      echo "$(basename "$1")'s libmaplibre.so is build id '${MLN_GOT:-unreadable}', not the patched AAR's '$MLN_WANT' ($MLN_AAR); refusing" >&2; return 1; }
    MLN_WHAT="patched, $(basename "$MLN_AAR")"
  else MLN_WHAT=stock; fi
  echo "libmaplibre.so build id $MLN_GOT ($MLN_WHAT)"
}
# --check-maplibre=<apk|aab>: only that proof, on an archive already built (and the tool's own test)
for a in "$@"; do
  case $a in --check-maplibre=*) f=${a#--check-maplibre=}
    case $f in *.aab) mln_check "$f" base/lib/arm64-v8a/libmaplibre.so ;; *) mln_check "$f" lib/arm64-v8a/libmaplibre.so ;; esac
    exit $? ;;
  esac
done
# (T538) this version's changelog bullets as JSON (node strips the file's types; the file has no imports): the version
# file's `notes`, the Play release notes and the email, from one place
notes_json() { node -e 'import(process.argv[1]).then((m)=>{const e=m.CHANGELOG.find((x)=>x.version===process.argv[2]);process.stdout.write(JSON.stringify(e?e.notes:[]))})' "$1/app/packages/core/src/changelog.ts" "$2"; }
WR="npx --prefix app wrangler"

# (T538) --publish-only: redo only play.json + the email for the Play build already uploaded
if [[ -n $PUBLISH_ONLY ]]; then
  [[ -n $PLAY ]] || { echo "build-apk: --publish-only is for a --play build (play.json + email)" >&2; exit 2; }
  PJ=app/dist/aab/play.json
  [[ -f $PJ ]] || { echo "build-apk --publish-only: no $PJ (the build writes it before the upload); nothing to publish" >&2; exit 1; }
  echo "build-apk --publish-only: $(cat "$PJ")"
  # never put back an OLDER build's file over what Play builds read now
  LOCALB=$(python3 -c 'import json,sys;print(json.load(open(sys.argv[1]))["build"])' "$PJ")
  PUBB=$(curl -fsS -A bc-fishing-build-apk "$BASE/play.json" | python3 -c 'import json,sys;print(json.load(sys.stdin)["build"])') \
    || { echo "build-apk --publish-only: cannot read the published $BASE/play.json; refused" >&2; exit 1; }
  (( LOCALB >= PUBB )) || { echo "build-apk --publish-only: $PJ is build $LOCALB, older than the published build $PUBB; refused" >&2; exit 1; }
  if [[ -n $DRY ]]; then echo "[dry-run] put $BUCKET/app/android/play.json; email via $FEEDS/notify/apk${EMAIL:+}"; exit 0; fi
  $WR r2 object put --remote "$BUCKET/app/android/play.json" --file "$PJ" --content-type "application/json" --cache-control "no-cache"
  if [[ -n $EMAIL ]]; then
    TEST_URL=$(tr -d '\n' < "$SECRETS/play-test-url" 2>/dev/null || echo "$PLAY_STORE_URL")
    BODY=$(U="$TEST_URL" python3 -c 'import json,os,sys;v=json.load(open(sys.argv[1]));print(json.dumps({"channel":"play","version":v["version"],"build":v["build"],"sha":v["sha"],"date":v["date"],"size":"-","url":os.environ["U"],"changes":v.get("notes",[])+(["MapLibre build id "+v["maplibre"]] if v.get("maplibre") else [])}))' "$PJ")
    TOK=$(tr -d '\n' < "$REPO/$TOKF" 2>/dev/null || true)
    code=$(curl -s -o /dev/null -w '%{http_code}' -X POST -H "Authorization: Bearer $TOK" -H "Content-Type: application/json" -d "$BODY" "$FEEDS/notify/apk" || true)
    echo "email: HTTP $code (200 = sent)"; [[ $code == 200 ]] || exit 1
  fi
  exit 0
fi

# (T538) THE PRECHECK, before the lock: every failure listed, then one exit
if [[ -z ${BUILD_APK_INNER:-} ]]; then
  set +e      # every check runs and is listed; the block decides once, at its end (set -e again there)
  pf=()
  bad() { pf+=("$*"); echo "  FAIL $*"; }
  ok() { echo "  ok   $*"; }
  echo "build-apk: precheck (before the heavy lock)"
  VER0=$(node -p "require('./$M/app.json').expo.version")
  if out=$(node scripts/check-changelog.mjs 2>&1); then ok "$out"
  elif [[ -n $NONOTES ]]; then ok "changelog: SKIPPED (--no-notes): $NONOTES — $out"
  else bad "$out (--no-notes=<reason> goes on)"; fi
  if [[ -n $PLAY && -z $PROD ]]; then
    PUB=$(curl -fsS -A bc-fishing-build-apk "$BASE/play.json" | python3 -c 'import json,sys;print(json.load(sys.stdin)["version"])') \
      || PUB=""
    if [[ -z $PUB ]]; then bad "cannot read the published Play version ($BASE/play.json)"
    elif [[ $PUB == "$VER0" && -z $SAMEVER ]]; then bad "app.json's version $VER0 is the one Play builds already read ($BASE/play.json): bump expo.version + a changelog entry, or --same-version=<reason>"
    else ok "version $VER0 (Play builds read $PUB)${SAMEVER:+ — same version allowed: $SAMEVER}"; fi
  fi
  if [[ -n $PLAY ]]; then
    PROPS=$SECRETS/upload-keystore.properties
    STORE=$(sed -n 's/^storeFile=//p' "$PROPS" 2>/dev/null)
    [[ -n $STORE && $STORE != /* ]] && STORE=$(dirname "$PROPS")/$STORE
    if [[ -f $PROPS && -f $SECRETS/upload_certificate.pem && -n $STORE && -f $STORE ]]; then ok "upload keystore, its properties and certificate"
    else bad "upload signing: $PROPS, its storeFile and $SECRETS/upload_certificate.pem must exist (T267)"; fi
    git diff --quiet HEAD -- "$M/app.json" && ok "app.json committed" || bad "$M/app.json has uncommitted edits; commit them first (the bump commits only app.json)"
    if [[ -z $NOUP ]]; then
      if [[ ! -f $SECRETS/play-service-account.json ]]; then bad "no Play service account ($SECRETS/play-service-account.json)"
      elif [[ -n $DRY ]]; then ok "Play service account (the Play call is not made in a dry run)"
      elif ONPLAY=$(.venv/bin/python deploy/staging/play-upload.py --package $PKG --max-version-code 2>&1); then ok "Play answers (highest versionCode $ONPLAY)"
      else bad "Play did not answer: ${ONPLAY: -200}"; fi
    fi
  else
    [[ -f $M/android/app/debug.keystore ]] && ok "debug keystore" || bad "missing $M/android/app/debug.keystore (the shared debug keystore; never a fresh key)"
  fi
  if [[ -z $NOUP ]]; then
    # whoami exits 0 when logged out too: its words decide (nothing it prints is kept: no token, no email)
    if [[ $($WR whoami 2>&1) == *"You are logged in"* ]]; then ok "Cloudflare (wrangler) login"
    else bad "wrangler is not logged in (npx --prefix app wrangler login): the R2 puts would fail AFTER the build"; fi
    if [[ -n $EMAIL ]]; then [[ -s $TOKF ]] && ok "run token ($TOKF)" || bad "no run token at $TOKF (the email); --no-email goes on"; fi
  fi
  if [[ -n $MLN_AAR ]]; then
    [[ -n $READELF && -x $READELF ]] && ok "llvm-readelf ($READELF)" || bad "no llvm-readelf under $ANDROID_HOME/ndk: the MapLibre build id cannot be proved"
    MLN_WANT=$([[ -n $READELF ]] && mln_id "$MLN_AAR" jni/arm64-v8a/libmaplibre.so)
    [[ -n $MLN_WANT ]] && ok "patched MapLibre AAR, build id $MLN_WANT" || bad "cannot read the build id of $MLN_AAR"
  fi
  dirty=$(git status --porcelain --untracked-files=all -- app/ | grep -v '^!!' || true)
  if [[ -z $dirty ]]; then ok "no uncommitted app/ paths"
  else
    echo "  uncommitted app/ paths (the build is a clean worktree of HEAD: these are LEFT OUT):"; sed 's/^/       /' <<<"$dirty" | head -20
    [[ -n $UNCOMMITTED ]] && ok "left out on purpose (--uncommitted): $UNCOMMITTED" || bad "$(grep -c . <<<"$dirty") uncommitted app/ path(s); commit them, or --uncommitted=<reason>"
  fi
  set -e
  if (( ${#pf[@]} )); then
    if [[ -n $DRY ]]; then echo "[dry-run] WOULD STOP: ${#pf[@]} precheck failure(s)"
    else echo "build-apk: precheck FAILED (${#pf[@]}) — the lock was not taken, nothing was built" >&2; exit 1; fi
  else echo "build-apk: precheck ok"; fi
  [[ -n $PRECHECK_ONLY ]] && exit 0
fi
if [[ -z ${BUILD_APK_INNER:-} ]]; then
  # (T533) CI on HEAD, before the lock: red (or the newest finished run red when HEAD has none) stops; running / no run
  # warns (scripts/ci_status.py). --no-ci-check=<reason> goes on, printed. A dry run shows it and goes on.
  if [[ -n $NOCI ]]; then echo "build-apk: CI check SKIPPED (--no-ci-check): $NOCI"; export CI_CHECK_SKIP="build-apk --no-ci-check: $NOCI"
  elif ! .venv/bin/python scripts/ci_status.py; then
    if [[ -n $DRY ]]; then echo "[dry-run] WOULD STOP: CI (above)"
    else echo "build-apk: CI is red or unreadable (above) — nothing was built; --no-ci-check=<reason> goes on" >&2; exit 1; fi
  fi
  # (T533) fast-fail's "changed" = everything since the last build of this kind was made from (the last Play build's
  # commit for --play, else the last sideload APK's), not only the unpushed commits. Said, never guessed silently.
  if [[ -n $PLAY ]]; then
    FFB=$(cat app/dist/apk/last-play-sha 2>/dev/null || true); FFB_WHAT="the last Play build (app/dist/apk/last-play-sha)"
    if [[ -z $FFB ]]; then   # not recorded before T533: the commit of that build's versionCode bump
      LASTCODE=$(cat "$SECRETS/play-last-version-code" 2>/dev/null || true)
      [[ -n $LASTCODE ]] && FFB=$(git log -1 --format=%H --grep "^app: versionCode $LASTCODE for Google Play" || true)
      FFB_WHAT="the last Play build's versionCode $LASTCODE bump (no last-play-sha recorded)"
    fi
  else
    FFB=$(cat app/dist/apk/last-sha 2>/dev/null || true); FFB_WHAT="the last sideload APK (app/dist/apk/last-sha)"
  fi
  if [[ -n $FFB ]] && git cat-file -e "$FFB^{commit}" 2>/dev/null; then
    export FAST_FAIL_BASE=$FFB; echo "build-apk: fast-fail base ${FFB:0:12}, $FFB_WHAT"
  else
    echo "build-apk: fast-fail base: none found for $FFB_WHAT — its default (the unpushed commits), NOT since the last build"
  fi
  # (T535) heavy.sh runs fast-fail before every heavy job: told it ran here (FAST_FAIL_DONE) or why it was skipped
  if [[ -n $NOFF ]]; then echo "build-apk: fast-fail SKIPPED (--no-fast-fail): $NOFF"; export HEAVY_NO_FAST_FAIL="build-apk --no-fast-fail: $NOFF"
  elif [[ -n $DRY ]]; then echo "[dry-run] scripts/fast-fail.sh"
  else scripts/fast-fail.sh || { echo "build-apk: scripts/fast-fail.sh failed (above) — nothing was built" >&2; exit 1; }
    FAST_FAIL_DONE=$(git rev-parse HEAD); export FAST_FAIL_DONE
  fi
fi
if [[ -z ${BUILD_APK_INNER:-} && -z $DRY ]]; then
  export BUILD_APK_INNER=1
  exec scripts/heavy.sh build-apk 20 -- "$0" "$@"
fi
export EXPO_PUBLIC_APP_ENV=staging EXPO_PUBLIC_ENV_SWITCH=1 EXPO_PUBLIC_CONTACT=${EXPO_PUBLIC_CONTACT:-support@canifishthis.ca}   # the store contact (T244)
export EXPO_PUBLIC_MAP_LAB=1   # (T420) the map lab: long-press the map's © chip (staging only; app.config.js refuses it in production)
