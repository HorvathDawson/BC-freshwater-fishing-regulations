#!/bin/bash
# STAGING ONLY: build a release arm64 APK of the app reading STAGING data (T232 env, switch on, T251 version stamp) and
# publish it to bc-fishing-regulations-staging under app/android/ (served by the staging data worker):
#   https://data-staging.canifishthis.ca/app/android/index.html   (link, version, date, size, install steps)
#   .../app/android/latest.apk  and  canifishthis-staging-<version>-<sha>.apk
# Signed with Expo's debug keystore (android/app/debug.keystore, gitignored; same key every build, so an update installs
# over the previous one). Sideload only. HEAVY: wrapped in scripts/heavy.sh (waits for the machine lock).
# After upload it emails the owner the link (POST /notify/apk on the staging feeds worker, RUN_TOKEN from
# app/workers/feeds/.run-token) unless --no-email; a failed email only warns.
# Builds COMMITTED HEAD only: a temporary git worktree at HEAD (other lanes' uncommitted edits never enter the APK), removed
# on exit/failure by a trap. Prints the sha it builds. node_modules via `pnpm install --offline --frozen-lockfile` in the
# worktree; the gitignored android/ is regenerated by `expo prebuild` there, then the repo's debug.keystore (same signing
# key, so updates install over) and the SDK local.properties are copied in.
# Usage: deploy/staging/build-apk.sh [--play] [--no-upload] [--no-email] [--dry-run]   (--dry-run prints the steps, builds nothing)
#
# (T267) --play: Google Play INTERNAL TESTING instead of the sideload page. Bumps android.versionCode (= ios.buildNumber)
# in app.json past max(app.json, ~/.canifishthis/play-last-version-code, the highest code Play holds) and commits ONLY
# app.json (refuses when app.json has uncommitted edits), then builds that HEAD as an AAB (bundleRelease) signed with the
# UPLOAD key named by ~/.canifishthis/upload-keystore.properties (plugins/with-upload-signing.js; the build refuses an AAB
# not signed by upload_certificate.pem), and uploads it to the internal track (deploy/staging/play-upload.py, service
# account ~/.canifishthis/play-service-account.json) with release notes = git log since the last Play upload, then
# emails the owner the tester link (~/.canifishthis/play-test-url, else the store page). --no-upload keeps the AAB at
# app/dist/aab/ (the FIRST upload must be done by hand in Play Console). Without --play nothing here changes: the APK is
# still debug-signed for sideloading.
set -euo pipefail
cd "$(dirname "$0")/../.."
REPO=$PWD
if [[ " $* " == *" --dry-run "* ]]; then DRY=1; else DRY=; fi
if [[ " $* " == *" --play "* ]]; then PLAY=1; else PLAY=; fi
if [[ " $* " == *" --no-upload "* ]]; then NOUP=1; else NOUP=; fi
SECRETS=$HOME/.canifishthis
PKG=ca.canifishthis.app
PLAY_STORE_URL="https://play.google.com/store/apps/details?id=$PKG"
if [[ -z ${BUILD_APK_INNER:-} && -z $DRY ]]; then
  export BUILD_APK_INNER=1
  exec scripts/heavy.sh build-apk 20 -- "$0" "$@"
fi
BUCKET=bc-fishing-regulations-staging            # hardcoded: never a production bucket
BASE=https://data-staging.canifishthis.ca/app/android
export JAVA_HOME=${JAVA_HOME:-"/Applications/Android Studio.app/Contents/jbr/Contents/Home"}
export ANDROID_HOME=${ANDROID_HOME:-$HOME/Library/Android/sdk}
export EXPO_PUBLIC_APP_ENV=staging EXPO_PUBLIC_ENV_SWITCH=1 EXPO_PUBLIC_CONTACT=${EXPO_PUBLIC_CONTACT:-support@canifishthis.ca}   # the store contact (T244)
# (T263) "Get the new test build" (Update the app, in a staging build) opens this page
export EXPO_PUBLIC_DEV_APK_URL=${EXPO_PUBLIC_DEV_APK_URL:-$BASE/index.html}
M=app/apps/mobile
if [[ -n $PLAY ]]; then
  export EXPO_PUBLIC_DEV_APK_URL=$PLAY_STORE_URL
  PROPS=$SECRETS/upload-keystore.properties
  [[ -f $PROPS && -f $SECRETS/upload_certificate.pem ]] || { echo "missing $PROPS or upload_certificate.pem (T267)" >&2; exit 1; }
  git diff --quiet HEAD -- "$M/app.json" || { echo "$M/app.json has uncommitted edits; commit them first (the bump commits only app.json)" >&2; exit 1; }
  CUR=$(node -p "require('./$M/app.json').expo.android.versionCode")
  LAST=$(cat "$SECRETS/play-last-version-code" 2>/dev/null || echo 0)
  ONPLAY=0
  if [[ -z $NOUP && -z $DRY ]]; then
    ONPLAY=$(.venv/bin/python deploy/staging/play-upload.py --package $PKG --max-version-code) || { echo "could not ask Play for its versionCodes" >&2; exit 1; }
  fi
  NEXT=$(( (CUR > LAST ? CUR : LAST) )); NEXT=$(( (NEXT > ONPLAY ? NEXT : ONPLAY) + 1 ))
  echo "versionCode: app.json $CUR, last Play build $LAST, on Play $ONPLAY -> $NEXT"
  if [[ -n $DRY ]]; then echo "[dry-run] set android.versionCode=$NEXT ios.buildNumber=$NEXT; git commit -- $M/app.json"
  else
    N=$NEXT node -e '
      const fs=require("fs"),p=process.argv[1],n=process.env.N;let s=fs.readFileSync(p,"utf8");
      const a=s.replace(/("versionCode":\s*)\d+/,"$1"+n).replace(/("buildNumber":\s*")\d+(")/,"$1"+n+"$2");
      if(a===s||!/"versionCode":\s*\d+/.test(a))throw new Error("versionCode not found");fs.writeFileSync(p,a);' "$M/app.json"
    git commit -q -m "app: versionCode $NEXT for Google Play internal testing (build-apk.sh --play)

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>" -- "$M/app.json"
  fi
fi
SHA_FULL=$(git rev-parse HEAD)
echo "building committed HEAD $SHA_FULL (uncommitted working-tree edits are NOT included)"
WT=${TMPDIR:-/tmp}/build-apk-wt-$$
step() { if [[ -n $DRY ]]; then echo "[dry-run] $*"; else "$@"; fi; }
cleanup() { if [[ -z $DRY ]]; then cd "$REPO" && git worktree remove --force "$WT" 2>/dev/null || rm -rf "$WT"; git worktree prune; fi; }
trap cleanup EXIT
step git worktree add --detach "$WT" "$SHA_FULL"
[[ -n $DRY ]] || cd "$WT"
VER=$(node -p "require('./$M/app.json').expo.version")
CODE=$(node -p "require('./$M/app.json').expo.android.versionCode")
SHA=$(git rev-parse --short HEAD)
export EXPO_PUBLIC_GIT_SHA=$SHA_FULL
DATE=$(date -u +%F)
OUT=$REPO/app/dist/apk; [[ -n $DRY ]] || mkdir -p "$OUT"
NAME="canifishthis-staging-$VER-$SHA.apk"
[[ -n $PLAY ]] && { OUT=$REPO/app/dist/aab; [[ -n $DRY ]] || mkdir -p "$OUT"; NAME="canifishthis-$VER-$CODE-$SHA.aab"; }
if [[ -n $DRY && -n $PLAY ]]; then
  echo "[dry-run] (cd \$WT/app && pnpm install --offline --frozen-lockfile); expo prebuild (plugins/with-upload-signing.js)"
  echo "[dry-run] (cd \$WT/$M/android && CANIFISHTHIS_UPLOAD_PROPERTIES=$SECRETS/upload-keystore.properties ./gradlew bundleRelease)"
  echo "[dry-run] check the AAB is signed by $SECRETS/upload_certificate.pem; copy -> $OUT/$NAME"
  echo "[dry-run] upload to Play track internal with notes from git log (unless --no-upload); email (unless --no-email)"
  exit 0
fi
if [[ -n $DRY ]]; then
  echo "[dry-run] (cd \$WT/app && pnpm install --offline --frozen-lockfile)"
  echo "[dry-run] (cd \$WT/$M && npx expo prebuild --platform android --no-install)"
  echo "[dry-run] cp $REPO/$M/android/app/debug.keystore \$WT/$M/android/app/; sdk.dir=$ANDROID_HOME > android/local.properties"
  echo "[dry-run] (cd \$WT/$M/android && ./gradlew assembleRelease -PreactNativeArchitectures=arm64-v8a --max-workers=4)"
  echo "[dry-run] copy app-release.apk -> $OUT/$NAME, latest.apk, index.html; upload (unless --no-upload), email (unless --no-email)"
  exit 0
fi
KS="$REPO/$M/android/app/debug.keystore"
[[ -f $KS ]] || { echo "missing $KS (the shared debug keystore); refusing to sign with a fresh key" >&2; exit 1; }
(cd app && pnpm install --offline --frozen-lockfile)
cd "$M"
npx expo prebuild --platform android --no-install
cp "$KS" android/app/debug.keystore
echo "sdk.dir=$ANDROID_HOME" > android/local.properties
if [[ -n $PLAY ]]; then
  (cd android && CANIFISHTHIS_UPLOAD_PROPERTIES=$PROPS ./gradlew bundleRelease -PreactNativeArchitectures=${PLAY_ABIS:-arm64-v8a} --max-workers=4 -Dorg.gradle.workers.max=4)
  cd "$WT"
  AAB=$M/android/app/build/outputs/bundle/release/app-release.aab
  KT="$JAVA_HOME/bin/keytool"
  want=$("$KT" -printcert -file "$SECRETS/upload_certificate.pem" | awk '/SHA256:/{print $2; exit}')
  got=$("$KT" -printcert -jarfile "$AAB" | awk '/SHA256:/{print $2; exit}')
  [[ -n $want && $want == "$got" ]] || { echo "AAB is not signed by the upload key (got '$got', want '$want'); refusing" >&2; exit 1; }
  cp "$AAB" "$OUT/$NAME"; cp "$OUT/$NAME" "$OUT/latest.aab"
  echo "$CODE" > "$SECRETS/play-last-version-code"
  SIZE=$(stat -f%z "$OUT/$NAME"); MB=$(awk "BEGIN{printf \"%.1f\", $SIZE/1048576}")
  echo "built $OUT/$NAME (versionCode $CODE, $MB MB, signed by upload key $want)"
  [[ -n $NOUP ]] && exit 0
  PREV=$(cat "$OUT/last-play-sha" 2>/dev/null || true)
  if [[ -n $PREV ]] && git cat-file -e "$PREV^{commit}" 2>/dev/null; then RANGE="$PREV..HEAD"; else RANGE="-10"; fi
  CH=$(git log $RANGE --no-merges -10 --format=%s | grep -v '^app: versionCode .* for Google Play' | cut -c1-160 || true)
  NOTES=$OUT/notes-$CODE.txt; { echo "Staging build $VER ($CODE), $SHA"; echo "$CH" | sed 's/^/- /'; } | cut -c1-500 > "$NOTES"
  "$REPO/.venv/bin/python" "$REPO/deploy/staging/play-upload.py" --aab "$OUT/$NAME" --package $PKG --track internal --notes-file "$NOTES"
  echo "$SHA_FULL" > "$OUT/last-play-sha"
  TEST_URL=$(tr -d '\n' < "$SECRETS/play-test-url" 2>/dev/null || echo "$PLAY_STORE_URL")
  if [[ " $* " != *" --no-email "* ]]; then
    export V=$VER B=$CODE S=$SHA D=$DATE SZ="$MB MB" U="$TEST_URL" CH
    BODY=$(python3 -c 'import json,os;e=os.environ;print(json.dumps({"channel":"play","version":e["V"],"build":e["B"],"sha":e["S"],"date":e["D"],"size":e["SZ"],"url":e["U"],"changes":e["CH"].splitlines()}))')
    TOK=$(tr -d '\n' < "$REPO/app/workers/feeds/.run-token" 2>/dev/null || true)   # the REPO's: the build worktree has no gitignored token
    code=$(curl -s -o /dev/null -w '%{http_code}' -X POST -H "Authorization: Bearer $TOK" -H "Content-Type: application/json" \
      -d "$BODY" https://bc-fishing-feeds-staging.horvath-dawson.workers.dev/notify/apk || true)
    echo "email: HTTP $code (200 = sent)"
  fi
  echo "uploaded versionCode $CODE to Play internal testing ($TEST_URL)"
  exit 0
fi
(cd android && ./gradlew assembleRelease -PreactNativeArchitectures=arm64-v8a --max-workers=4 -Dorg.gradle.workers.max=4)
cd "$WT"
cp "$M/android/app/build/outputs/apk/release/app-release.apk" "$OUT/$NAME"
cp "$OUT/$NAME" "$OUT/latest.apk"
SIZE=$(stat -f%z "$OUT/$NAME"); MB=$(awk "BEGIN{printf \"%.1f\", $SIZE/1048576}")
cat > "$OUT/index.html" <<HTML
<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>canifishthis Android (staging)</title>
<body style="font:16px/1.5 system-ui;max-width:34em;margin:2em auto;padding:0 16px">
<h1>canifishthis for Android <small>(staging)</small></h1>
<p><a href="latest.apk" style="font-size:1.3em"><b>Download the APK</b></a><br>
Version $VER (build $CODE), commit $SHA, built $DATE, $MB MB, arm64 phones.<br>
Pinned copy: <a href="$NAME">$NAME</a></p>
<p>This build reads <b>staging</b> data (data-staging.canifishthis.ca) and has the environment switch on About.</p>
<h2>Install</h2>
<ol><li>Open this page in Chrome on the phone and tap Download.</li>
<li>When asked, allow Chrome to <b>install unknown apps</b> (Settings, Apps, Chrome, Install unknown apps).</li>
<li>Open the downloaded file and tap Install. If Play Protect warns, choose "Install anyway" (the app is not from the Play Store).</li>
<li>Updates: install a newer APK from this page over the old one; your saved spots stay. The app also updates its data by itself.</li></ol>
</body>
HTML
[[ " $* " == *" --no-upload "* ]] && { echo "built $OUT/$NAME ($MB MB)"; exit 0; }
W="npx --prefix app wrangler r2 object put --remote"
APK=application/vnd.android.package-archive
$W "$BUCKET/app/android/$NAME" --file "$OUT/$NAME" --content-type $APK --content-disposition "attachment; filename=\"$NAME\"" --cache-control "public, max-age=31536000, immutable"
$W "$BUCKET/app/android/latest.apk" --file "$OUT/latest.apk" --content-type $APK --content-disposition "attachment; filename=\"canifishthis-staging.apk\"" --cache-control "no-cache"
$W "$BUCKET/app/android/index.html" --file "$OUT/index.html" --content-type "text/html; charset=utf-8" --cache-control "no-cache"
curl -sI "$BASE/latest.apk" | head -8
if [[ " $* " != *" --no-email "* ]]; then
  PREV=$(cat "$OUT/last-sha" 2>/dev/null || true)
  if [[ -n $PREV ]] && git cat-file -e "$PREV^{commit}" 2>/dev/null; then RANGE="$PREV..HEAD"; else RANGE="-10"; fi
  export V=$VER B=$CODE S=$SHA D=$DATE SZ="$MB MB" U="$BASE/latest.apk"
  export CH=$(git log $RANGE --no-merges -10 --format=%s | cut -c1-160)
  BODY=$(python3 -c 'import json,os;e=os.environ;print(json.dumps({"version":e["V"],"build":e["B"],"sha":e["S"],"date":e["D"],"size":e["SZ"],"url":e["U"],"changes":e["CH"].splitlines()}))')
  TOK=$(tr -d '\n' < "$REPO/app/workers/feeds/.run-token" 2>/dev/null || true)   # the REPO's: the build worktree has no gitignored token
  code=$(curl -s -o /dev/null -w '%{http_code}' -X POST -H "Authorization: Bearer $TOK" -H "Content-Type: application/json" \
    -d "$BODY" https://bc-fishing-feeds-staging.horvath-dawson.workers.dev/notify/apk || true)
  echo "email: HTTP $code (200 = sent)"
fi
echo "$SHA_FULL" > "$OUT/last-sha"
echo "published $BASE/index.html  ($NAME, $MB MB)"
