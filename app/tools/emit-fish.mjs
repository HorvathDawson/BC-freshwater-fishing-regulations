#!/usr/bin/env node
/**
 * THE FISH MANIFEST, EMITTED TWICE (T20).
 *
 *   node tools/emit-fish.mjs            -> writes both files
 *   node tools/emit-fish.mjs --check    -> exits 1 when either committed file differs
 *
 * One source, `apps/mobile/assets/fish/manifest.json`, two outputs:
 *   - `packages/core/src/regs/fish.generated.ts`: which species codes have a picture, with
 *     caption and credit. Core never imports an asset, so it can know this on every platform.
 *   - `apps/mobile/src/fishImages.generated.ts`: the `require()` per picture. Metro resolves
 *     `require` STATICALLY, so every path is a literal — no template string, no loop.
 *     `apps/mobile` is the only layer allowed to register assets (layers.json); components
 *     get the map as a `FishImages` prop.
 *
 * Images with `code: null` have no species row and are skipped. Keys are sorted by code for a
 * stable diff; images keep manifest order within a code (the first is the one a row shows).
 * Every string goes through JSON.stringify — never hand-escaped.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const app = fileURLToPath(new URL("..", import.meta.url));
export const MANIFEST = `${app}apps/mobile/assets/fish/manifest.json`;
export const CORE_OUT = `${app}packages/core/src/regs/fish.generated.ts`;
export const MOBILE_OUT = `${app}apps/mobile/src/fishImages.generated.ts`;

const s = JSON.stringify;

/** code -> images in manifest order, codes sorted; null codes dropped. */
function byCode(manifest) {
  const out = new Map();
  for (const img of manifest.images) {
    if (img.code === null || img.code === undefined) continue;
    if (!out.has(img.code)) out.set(img.code, []);
    out.get(img.code).push(img);
  }
  return [...out.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

const nullable = (v) => (v === null || v === undefined ? "null" : s(v));

export function emit(manifest, sha) {
  const codes = byCode(manifest);

  const core = [
    "// GENERATED by app/tools/emit-fish.mjs from apps/mobile/assets/fish/manifest.json. Do not edit.",
    "// Regenerate with `pnpm fish:build`; `pnpm fish` (in `pnpm check`) fails when this is stale.",
    "",
    "/** One fish picture: what it shows and who made it. The asset itself lives in apps/mobile. */",
    "export interface FishImage { readonly file: string; readonly caption: string; readonly credit: string; readonly type: string;",
    "  readonly source: string; readonly phase: string | null; readonly standInFor: string | null; readonly width: number; readonly height: number }",
    "",
    "/** Species code -> its pictures, manifest order: the FIRST is the one every row shows. */",
    "export type FishManifest = Readonly<Record<string, readonly FishImage[]>>;",
    "",
    "/** sha256 of manifest.json's bytes, for `--check`. */",
    `export const FISH_MANIFEST_SHA256: string = ${s(sha)};`,
    "",
    "export const FISH: FishManifest = {",
    ...codes.map(([code, imgs]) => [
      `  ${s(code)}: [`,
      ...imgs.map((i) =>
        `    { file: ${s(i.file)}, caption: ${s(i.caption)}, credit: ${s(i.credit)}, type: ${s(i.type)}, ` +
        `source: ${s(i.source)}, phase: ${nullable(i.phase)}, standInFor: ${nullable(i.stand_in_for)}, ` +
        `width: ${Number(i.width)}, height: ${Number(i.height)} },`),
      "  ],",
    ].join("\n")),
    "};",
    "",
  ].join("\n");

  const mobile = [
    "// GENERATED by app/tools/emit-fish.mjs from apps/mobile/assets/fish/manifest.json. Do not edit.",
    "// Literal require() paths: Metro resolves them statically. Codes match FISH in @app/core.",
    'import type { ImageSourcePropType } from "react-native";',
    "",
    "export const FISH_IMAGES: Readonly<Record<string, readonly ImageSourcePropType[]>> = {",
    ...codes.map(([code, imgs]) =>
      `  ${s(code)}: [${imgs.map((i) => `require(${s(`../assets/fish/${i.file}`)})`).join(", ")}],`),
    "};",
    "",
  ].join("\n");

  return { core, mobile };
}

function main() {
  const bytes = readFileSync(MANIFEST);
  const sha = createHash("sha256").update(bytes).digest("hex");
  const { core, mobile } = emit(JSON.parse(bytes.toString("utf8")), sha);
  if (process.argv.includes("--check")) {
    const read = (p) => { try { return readFileSync(p, "utf8"); } catch { return null; } };
    if (read(CORE_OUT) !== core || read(MOBILE_OUT) !== mobile) {
      console.error("fish.generated.ts is stale — run pnpm fish:build");
      process.exit(1);
    }
    console.log("✓ fish.generated.ts current");
    return;
  }
  writeFileSync(CORE_OUT, core);
  writeFileSync(MOBILE_OUT, mobile);
  console.log(`wrote ${CORE_OUT}\nwrote ${MOBILE_OUT}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
