#!/usr/bin/env node
/**
 * THE FISH MANIFEST, EMITTED TWICE (T20).
 *
 *   node tools/emit-fish.mjs            -> writes both files
 *   node tools/emit-fish.mjs --check    -> exits 1 when either committed file differs
 *
 * One source, `apps/mobile/assets/fish/manifest.json`, two outputs:
 *   - `packages/core/src/regs/fish.generated.ts`: which species codes have a picture, with
 *     caption and credit. Core never imports an asset, so it can know this on every platform.
 *   - `apps/mobile/src/fishImages.generated.ts`: the `require()` per picture. Metro resolves
 *     `require` STATICALLY, so every path is a literal — no template string, no loop.
 *     `apps/mobile` is the only layer allowed to register assets (layers.json); components
 *     get the map as a `FishImages` prop.
 *
 * (T36) And the "What to look for" tips of the fish sheet (`FISH_TIPS`): page v36's own FISHART.SPECIES[code].tips
 * (pipeline/deliver/answers/reference/page_v36.js — the table the prototype's snapshot read, regs-v11/tools/snap.mjs),
 * evaluated from that file's FISHART block with a stub `window`; not in the store, never hand-written.
 *
 * (T38) And the hatch sheet's two drawings (`ADIPOSE_IMAGES`, by variant): the manifest rows `adipose-wild.webp` and
 * `adipose-clipped.webp` (code null: never a species picture; drawn by tools/emit-adipose.mjs). A manifest without
 * either is refused — the "Hatchery or wild?" sheet would draw two empty grounds.
 *
 * Images with `code: null` have no species row and are skipped. Keys are sorted by code for a
 * stable diff; images keep manifest order within a code (the first is the one a row shows).
 * Every string goes through JSON.stringify — never hand-escaped.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const app = fileURLToPath(new URL("..", import.meta.url));
export const MANIFEST = `${app}apps/mobile/assets/fish/manifest.json`;
export const CORE_OUT = `${app}packages/core/src/regs/fish.generated.ts`;
export const MOBILE_OUT = `${app}apps/mobile/src/fishImages.generated.ts`;
export const TIPS_SOURCE = `${app}../pipeline/deliver/answers/reference/page_v36.js`;

const s = JSON.stringify;

/** code -> images in manifest order, codes sorted; null codes dropped. */
function byCode(manifest) {
  const out = new Map();
  for (const img of manifest.images) {
    if (img.code === null || img.code === undefined) continue;
    if (!out.has(img.code)) out.set(img.code, []);
    out.get(img.code).push(img);
  }
  return [...out.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

/** page v36's FISHART block (`const FISHART = (() => { … })();`) evaluated alone: code -> its tips, codes sorted. */
export function fishTips(pageSrc) {
  const at = pageSrc.indexOf("const FISHART = (() => {"), end = pageSrc.indexOf("\n})();", at);
  if (at < 0 || end < 0) throw new Error("emit-fish: no FISHART block in page_v36.js");
  const FISHART = new Function("window", `${pageSrc.slice(at, end + 6)}\nreturn FISHART;`)({});
  return Object.fromEntries(Object.keys(FISHART.SPECIES).sort().map((c) => [c, [...(FISHART.SPECIES[c].tips ?? [])]]));
}

/** (T38) The hatch sheet's drawings, by variant: their manifest file names. */
export const ADIPOSE_FILES = { wild: "adipose-wild.webp", clipped: "adipose-clipped.webp" };

function adiposeFiles(manifest) {
  return Object.entries(ADIPOSE_FILES).map(([variant, file]) => {
    if (!manifest.images.some((i) => i.file === file)) throw new Error(`emit-fish: manifest.json has no ${file} (the hatch sheet's drawing)`);
    return [variant, file];
  });
}

const nullable = (v) => (v === null || v === undefined ? "null" : s(v));

const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** (T43) one picture's credit line — every OUTSIDE picture is credited. The app's own drawings (source "this app", the
 *  adipose figures, T38) are not credits: there is nobody else to credit, and the line would only repeat the app. */
export const credited = (i) => i.source !== "this app";
export const creditLine = (i) => `${i.caption}${i.phase ? ` · ${i.phase}` : ""} — ${i.credit} (${i.source})`;

export function emit(manifest, sha, tips) {
  const codes = byCode(manifest);
  const adipose = adiposeFiles(manifest);
  const credits = new Map(manifest.images.filter(credited).map((i) => [i.file, creditLine(i)]));

  const core = [
    "// GENERATED by app/tools/emit-fish.mjs from apps/mobile/assets/fish/manifest.json. Do not edit.",
    "// Regenerate with `pnpm fish:build`; `pnpm fish` (in `pnpm check`) fails when this is stale.",
    "",
    "/** One fish picture: what it shows and who made it. The asset itself lives in apps/mobile. */",
    "export interface FishImage { readonly file: string; readonly caption: string; readonly credit: string; readonly type: string;",
    "  readonly source: string; readonly phase: string | null; readonly standInFor: string | null; readonly width: number; readonly height: number }",
    "",
    "/** Species code -> its pictures, manifest order: the FIRST is the one every row shows. */",
    "export type FishManifest = Readonly<Record<string, readonly FishImage[]>>;",
    "",
    "/** sha256 of manifest.json's bytes, for `--check`. */",
    `export const FISH_MANIFEST_SHA256: string = ${s(sha)};`,
    "",
    "export const FISH: FishManifest = {",
    ...codes.map(([code, imgs]) => [
      `  ${s(code)}: [`,
      ...imgs.map((i) =>
        `    { file: ${s(i.file)}, caption: ${s(i.caption)}, credit: ${s(i.credit)}, type: ${s(i.type)}, ` +
        `source: ${s(i.source)}, phase: ${nullable(i.phase)}, standInFor: ${nullable(i.stand_in_for)}, ` +
        `width: ${Number(i.width)}, height: ${Number(i.height)} },`),
      "  ],",
    ].join("\n")),
    "};",
    "",
    "/** (T43) Picture file -> its credit line, \"<caption>[ · <phase>] — <credit> (<source>)\": the pictured fish (a stand-in by its own caption). */",
    "export const FISH_CREDIT_OF: Readonly<Record<string, string>> = {",
    ...[...credits].sort(([a], [b]) => cmp(a, b)).map(([file, line]) => `  ${s(file)}: ${s(line)},`),
    "};",
    "",
    "/** (T43) Every picture's credit line, sorted, de-duplicated: the app's one \"Fish pictures\" list. */",
    "export const FISH_CREDITS: readonly string[] = [",
    ...[...new Set(credits.values())].sort(cmp).map((line) => `  ${s(line)},`),
    "];",
    "",
    "/** (T36) Species code -> \"What to look for\" on its fish sheet: page v36's FISHART.SPECIES[code].tips. */",
    "export const FISH_TIPS: Readonly<Record<string, readonly string[]>> = {",
    ...Object.entries(tips).map(([code, ts]) => `  ${s(code)}: [${ts.map(s).join(", ")}],`),
    "};",
    "",
  ].join("\n");

  const mobile = [
    "// GENERATED by app/tools/emit-fish.mjs from apps/mobile/assets/fish/manifest.json. Do not edit.",
    "// Literal require() paths: Metro resolves them statically. Codes match FISH in @app/core.",
    'import type { ImageSourcePropType } from "react-native";',
    "",
    "export const FISH_IMAGES: Readonly<Record<string, readonly ImageSourcePropType[]>> = {",
    ...codes.map(([code, imgs]) =>
      `  ${s(code)}: [${imgs.map((i) => `require(${s(`../assets/fish/${i.file}`)})`).join(", ")}],`),
    "};",
    "",
    "/** (T38) The hatch sheet's two drawings (Wild · adipose fin there / Hatchery · clipped), by variant. */",
    "export const ADIPOSE_IMAGES: { readonly wild: ImageSourcePropType; readonly clipped: ImageSourcePropType } = {",
    ...adipose.map(([variant, file]) => `  ${variant}: require(${s(`../assets/fish/${file}`)}),`),
    "};",
    "",
  ].join("\n");

  return { core, mobile };
}

function main() {
  const bytes = readFileSync(MANIFEST);
  const sha = createHash("sha256").update(bytes).digest("hex");
  const { core, mobile } = emit(JSON.parse(bytes.toString("utf8")), sha, fishTips(readFileSync(TIPS_SOURCE, "utf8")));
  if (process.argv.includes("--check")) {
    const read = (p) => { try { return readFileSync(p, "utf8"); } catch { return null; } };
    if (read(CORE_OUT) !== core || read(MOBILE_OUT) !== mobile) {
      console.error("fish.generated.ts is stale — run pnpm fish:build");
      process.exit(1);
    }
    console.log("✓ fish.generated.ts current");
    return;
  }
  writeFileSync(CORE_OUT, core);
  writeFileSync(MOBILE_OUT, mobile);
  console.log(`wrote ${CORE_OUT}\nwrote ${MOBILE_OUT}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
