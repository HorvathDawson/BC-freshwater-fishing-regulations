/**
 * The v1 site's indexed URLs (`/waterbody/<watershed code or lake key>/`, 19,331 of them in Search Console's eyes) keep working:
 * each is ONE 301 to the best page of today's site, never a chain and never a 404.
 *
 *   water  - an item holding that code has a water page                     -> /water/<slug>
 *   region - none does (no rules today, or only a parent code is known)     -> /region/<n>
 *   home   - the code is unknown and names no region                        -> /
 *
 * `app/seo/legacy-crosswalk.json` (made by legacy-crosswalk.mjs from the registry) says which items hold each code; the slug
 * map says where an item lives. The pure `legacyRedirect` is what the edge worker (generated below) does, so a test holds
 * the shipped worker to the same answers.
 */
export type Crosswalk = Readonly<Record<string, readonly string[] | string | null>>;
export interface LegacyBuilt {
  /** "/waterbody/<id>" -> target path */
  readonly map: Readonly<Record<string, string>>;
  readonly counts: { readonly water: number; readonly region: number; readonly home: number };
}

export function legacyRedirects(cw: Crosswalk, pathOfItem: ReadonlyMap<string, string>, regions: ReadonlySet<number>): LegacyBuilt {
  const map: Record<string, string> = {};
  const counts = { water: 0, region: 0, home: 0 };
  for (const [old, v] of Object.entries(cw)) {
    const cands = typeof v === "string" ? [`r${v}`] : (v ?? []);
    const page = cands.map((c) => pathOfItem.get(c)).find((p) => p !== undefined);
    const region = cands.flatMap((c) => /^r(\d+)$/.test(c) ? [Number(c.slice(1))] : []).find((r) => regions.has(r));
    const to = page ?? (region !== undefined ? `/region/${region}` : "/");
    counts[page ? "water" : region !== undefined ? "region" : "home"]++;
    map[`/waterbody/${old}`] = to;
  }
  return { map, counts };
}

/** The 301 for a request path, or null when it is not a v1 path. Trailing slash and %-escapes are tolerated. */
export function legacyRedirect(map: Readonly<Record<string, string>>, pathname: string): { status: 301; to: string } | null {
  let p = pathname.length > 1 && pathname.endsWith("/") ? pathname.slice(0, -1) : pathname;
  try { p = decodeURI(p); } catch { /* keep it as sent */ }
  const to = Object.hasOwn(map, p) ? map[p] : undefined;
  return to === undefined ? null : { status: 301, to };
}

/**
 * The edge worker (Cloudflare Workers + static assets: `run_worker_first = ["/waterbody/*"]`). Cloudflare's `_redirects` holds
 * at most 2,000 static rules, far under 19k, so the map ships inside the worker. Anything not in the map falls through to the
 * assets (and their real 404).
 */
export function legacyWorker(map: Readonly<Record<string, string>>): string {
  return `// generated by tools/seo (legacy.ts): v1 /waterbody/<id>/ -> one 301. Do not edit.
const MAP = ${JSON.stringify(map)};
export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    let p = url.pathname.length > 1 && url.pathname.endsWith("/") ? url.pathname.slice(0, -1) : url.pathname;
    try { p = decodeURI(p); } catch (e) {}
    const to = Object.prototype.hasOwnProperty.call(MAP, p) ? MAP[p] : undefined;
    if (to !== undefined) return Response.redirect(url.origin + to, 301);
    return env.ASSETS.fetch(request);
  },
};
`;
}
