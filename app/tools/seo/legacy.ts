/**
 * The v1 site's indexed URLs (`/waterbody/<watershed code or lake key>/`, 19,331 of them in Search Console's eyes) keep working:
 * each is ONE 301 to the best page of today's site, never a chain and never a 404.
 *
 *   water  - an item holding that code has a water page                     -> /water/<slug>
 *   region - none does (no rules today, or only a parent code is known)     -> /region/<n>
 *   home   - the code is unknown and names no region                        -> /
 *
 * `app/seo/legacy-crosswalk.json` (made by legacy-crosswalk.mjs from the registry) says which items hold each code; the slug
 * map says where an item lives. The pure `legacyRedirect` is what the edge worker (generated below) does, so a test holds
 * the shipped worker to the same answers.
 */
export type Crosswalk = Readonly<Record<string, readonly string[] | string | null>>;
export interface LegacyBuilt {
  /** "/waterbody/<id>" -> target path */
  readonly map: Readonly<Record<string, string>>;
  readonly counts: { readonly water: number; readonly region: number; readonly home: number };
}

export function legacyRedirects(cw: Crosswalk, pathOfItem: ReadonlyMap<string, string>, regions: ReadonlySet<number>): LegacyBuilt {
  const map: Record<string, string> = {};
  const counts = { water: 0, region: 0, home: 0 };
  for (const [old, v] of Object.entries(cw)) {
    const cands = typeof v === "string" ? [`r${v}`] : (v ?? []);
    const page = cands.map((c) => pathOfItem.get(c)).find((p) => p !== undefined);
    const region = cands.flatMap((c) => /^r(\d+)$/.test(c) ? [Number(c.slice(1))] : []).find((r) => regions.has(r));
    const to = page ?? (region !== undefined ? `/region/${region}` : "/");
    counts[page ? "water" : region !== undefined ? "region" : "home"]++;
    map[`/waterbody/${old}`] = to;
  }
  return { map, counts };
}

/** The 301 for a request path, or null when it is not a v1 path. Trailing slash and %-escapes are tolerated. */
export function legacyRedirect(map: Readonly<Record<string, string>>, pathname: string): { status: 301; to: string } | null {
  let p = pathname.length > 1 && pathname.endsWith("/") ? pathname.slice(0, -1) : pathname;
  try { p = decodeURI(p); } catch { /* keep it as sent */ }
  const to = Object.hasOwn(map, p) ? map[p] : undefined;
  return to === undefined ? null : { status: 301, to };
}

/**
 * The edge worker (Cloudflare Workers + static assets: `run_worker_first = ["/waterbody/*"]`). Cloudflare's `_redirects` holds
 * at most 2,000 static rules, far under 19k, so the map ships inside the worker. Anything not in the map falls through to the
 * assets (and their real 404).
 */
/**
 * The site's worker (Cloudflare static assets run it first for `/waterbody/*` and `/water/*`):
 *   - v1 `/waterbody/<id>/` → one 301 (the map above);
 *   - (T279) `/water/<slug>` → the page's STORED COMPRESSED BYTES (`index.html.br` / `.gz`, compressed.ts) with their
 *     `Content-Encoding`, by the request's Accept-Encoding (brotli first); a client that takes neither gets the gzip
 *     inflated here. A slug with no page → the assets' answer (`_redirects`: a removed water's 301 to its region; else the 404).
 *   - (T487) `/gauge/<station>/card.png` → that gauge's share card as the feeds worker drew it (R2 `feeds/cards/<station>.png`,
 *     binding CARDS) — no drawing here; a card that is not there → the site's fixed card (`/share/gauge.png`, `x-card: site`)
 *     AND a marker under `private/cards-missing/` the feeds worker reports. `/gauge/<station>` or a stale slug → one 301 to
 *     the gauge's page.
 *   - any other path ending in `/` (the host runs the worker first for every path that ends in a slash too) → ONE 301 to the path without it: the
 *     assets' `drop-trailing-slash` would answer 307, a temporary redirect search engines do not consolidate.
 * Everything else is the assets' own answer.
 */
export function legacyWorker(map: Readonly<Record<string, string>>, htmlCache = "public, max-age=300, must-revalidate",
                             gauges: Readonly<Record<string, string>> = {}): string {
  return `// generated by tools/seo (legacy.ts): v1 /waterbody/<id>/ -> one 301; /water/<slug> -> its stored compressed page;
// (T487) /gauge/<station>/card.png -> the card the feeds worker drew (R2, binding CARDS), else the site card + a marker. Do not edit.
const MAP = ${JSON.stringify(map)};
const WATER = /^\\/water\\/[a-z0-9-]+$/;
const GAUGE = ${JSON.stringify(gauges)};
const GAUGE_PATH = /^\\/gauge\\/([A-Za-z0-9]+)(\\/[^/]*)?$/;
const CARD_CACHE = "public, max-age=900";
// (T487) a missing card: one marker per station under private/cards-missing/ (refreshed at most hourly), read back into the
// owner's digest by the feeds worker's gauge run (src/gauges/card/card.ts cardEvents). No binding: said in the log.
async function missing(env, st) {
  if (!env.CARDS) { console.error("gauge card: no CARDS binding on the site worker; " + st + " answered with the site card"); return; }
  const key = "private/cards-missing/" + st + ".json", at = new Date().toISOString();
  const was = await env.CARDS.get(key);
  let m = { station: st, first: at, last: at, count: 0 };
  if (was) { try { m = await was.json(); } catch (e) { console.error("gauge card: marker " + key + " unreadable, replaced: " + e); } }
  if (m.count && Date.parse(at) - Date.parse(m.last) < 3600000) return;
  m.last = at; m.count = (m.count || 0) + 1;
  await env.CARDS.put(key, JSON.stringify(m), { httpMetadata: { contentType: "application/json" } });
}
async function card(request, env, ctx, url, st) {
  const obj = env.CARDS ? await env.CARDS.get("feeds/cards/" + st + ".png") : null;
  if (obj) {
    const headers = new Headers({ "content-type": "image/png", "cache-control": CARD_CACHE, etag: obj.httpEtag });
    return new Response(request.method === "HEAD" ? null : obj.body, { status: 200, headers });
  }
  ctx.waitUntil(missing(env, st).catch((e) => console.error("gauge card: marker for " + st + " not written: " + e)));
  const site = await env.ASSETS.fetch(new Request(url.origin + "/share/gauge.png"));
  const headers = new Headers(site.headers);
  headers.set("cache-control", "public, max-age=300");
  headers.set("x-card", "site");
  return new Response(request.method === "HEAD" ? null : site.body, { status: site.status, headers });
}
function gauge(request, env, ctx, url, p) {
  const m = GAUGE_PATH.exec(p);
  const want = m && Object.prototype.hasOwnProperty.call(GAUGE, m[1]) ? GAUGE[m[1]] : undefined;
  if (want === undefined) return env.ASSETS.fetch(request);
  if (m[2] === "/card.png") return card(request, env, ctx, url, m[1]);
  // the station alone, or a slug the gauge no longer has (renamed): one 301 to its page
  if (p !== want) return Response.redirect(url.origin + want + url.search, 301);
  return env.ASSETS.fetch(request);
}
async function water(request, env, url, p) {
  const ae = request.headers.get("accept-encoding") || "";
  const br = /\\bbr\\b/.test(ae), gz = /\\bgzip\\b/.test(ae);
  const stored = await env.ASSETS.fetch(new Request(url.origin + p + "/index.html." + (br ? "br" : "gz")));
  if (stored.status !== 200) return env.ASSETS.fetch(request);
  const headers = new Headers(stored.headers);
  headers.set("content-type", "text/html; charset=utf-8");
  headers.set("cache-control", ${JSON.stringify(htmlCache)});
  headers.set("vary", "Accept-Encoding");
  if (!br && !gz) {
    headers.delete("content-encoding"); headers.delete("content-length");
    return new Response(stored.body.pipeThrough(new DecompressionStream("gzip")), { status: 200, headers });
  }
  headers.set("content-encoding", br ? "br" : "gzip");
  return new Response(request.method === "HEAD" ? null : stored.body, { status: 200, headers, encodeBody: "manual" });
}
export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    let p = url.pathname.length > 1 && url.pathname.endsWith("/") ? url.pathname.slice(0, -1) : url.pathname;
    try { p = decodeURI(p); } catch (e) {}
    const to = Object.prototype.hasOwnProperty.call(MAP, p) ? MAP[p] : undefined;
    if (to !== undefined) return Response.redirect(url.origin + to, 301);
    // one URL form, no trailing slash: a PERMANENT redirect (the assets' own drop-trailing-slash answers 307)
    if (url.pathname.length > 1 && url.pathname.endsWith("/")) return Response.redirect(url.origin + url.pathname.replace(/\\/+$/, "") + url.search, 301);
    if (WATER.test(p)) return water(request, env, url, p);
    if (p.startsWith("/gauge/")) return gauge(request, env, ctx, url, p);
    return env.ASSETS.fetch(request);
  },
};
`;
}
