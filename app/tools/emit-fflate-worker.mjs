#!/usr/bin/env node
/**
 * (T910) THE WEB'S RULES WORKER CARRIES FFLATE'S OWN UMD BUILD: `packages/data/src/regs/fflateWorker.generated.ts` is
 * `node_modules/fflate/umd/index.js` as a string, base64 (a worker made from a Blob cannot import the bundle's modules), so the
 * worker inflates with exactly the fflate the phone and the rest of the web use. `tools/rules-worker.test.ts` refuses a
 * module that is not the installed fflate's file (a package update fails the check until this is rerun).
 *
 *   node tools/emit-fflate-worker.mjs
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const app = fileURLToPath(new URL("..", import.meta.url));
export const FFLATE_WORKER_MODULE = `${app}packages/data/src/regs/fflateWorker.generated.ts`;

/** The installed fflate: its version and its UMD build's text. */
export function installedFflate() {
  const req = createRequire(`${app}packages/data/package.json`);
  // the package's root: its entry's folder, walked up to the package.json named fflate (no `./package.json` export)
  let dir = dirname(req.resolve("fflate"));
  while (!existsSync(join(dir, "package.json")) || JSON.parse(readFileSync(join(dir, "package.json"), "utf8")).name !== "fflate") {
    if (dirname(dir) === dir) throw new Error("emit-fflate-worker: no fflate package above its entry");
    dir = dirname(dir);
  }
  return { version: JSON.parse(readFileSync(join(dir, "package.json"), "utf8")).version, umd: readFileSync(join(dir, "umd/index.js"), "utf8") };
}

export function fflateWorkerModule({ version, umd }) {
  return `// GENERATED by app/tools/emit-fflate-worker.mjs from node_modules/fflate/umd/index.js. Do not edit.\n` +
    `// (T910) the web's rules worker (rulesDecode.web.ts) runs this: fflate ${version}, the same the bundle carries.\n` +
    // base64: the text names \`require('worker_threads')\` (fflate's node branch, never run in a browser worker), which the
    // boundaries gate would read as this package importing it
    `export const FFLATE_UMD_B64 = ${JSON.stringify(Buffer.from(umd, "utf8").toString("base64"))};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(FFLATE_WORKER_MODULE, fflateWorkerModule(installedFflate()));
  console.log(`emit-fflate-worker: wrote ${FFLATE_WORKER_MODULE}`);
}
