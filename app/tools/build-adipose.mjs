#!/usr/bin/env node
/**
 * (T886, owner 2026-11-18) THE "HATCHERY OR WILD?" SHEET'S TWO DRAWINGS, on the loading screen's coho.
 *
 *   node tools/build-adipose.mjs           -> `pnpm adipose:build`: draws them + writes adipose.generated.ts
 *   node tools/build-adipose.mjs --check   -> `pnpm adipose` (in `pnpm check`): writes nothing, fails on any drift
 *
 * The owner, on the rainbow trout they replace: "the how to tell hatchery fish is very smile creepy we want to make it
 * more realistic I think. Better shape more natural smile. Could use the salmon general shape from loading maybe?" The
 * drawing is `tools/fish-loader/adipose_art.py`: the owner's coho (`fish_loader.build()`) at rest, its face plain (a
 * straight closed mouth, a plain eye, one gill arc); the wild fish with a clear adipose fin, the clipped one with a bare
 * back and a small healed scar; the spot ringed on both and drawn again 2.5x in a close-up circle.
 *
 * COLOURS from the tokens, as the loader's (`tools/build-coho.mjs`): the fish in `color.ui.coho.ink` + `.red`, the ring in
 * `color.ui.accent`, per theme (never typed here: `tools/check-colours.mjs`). One pair of drawings per distinct trio,
 * named after the first theme that wears it (light first); the module maps every theme to its pair. Transparent ground: the
 * sheet's card shows through.
 *
 * SIZE: 1200 x 600 px (2:1: the fish along the bottom, a 2.5x close-up of the spot over its back; `AdiposeArt`'s box keeps
 * the aspect). The picture is at most `FISH_PICTURE.maxWidth` (360 dp) wide: 3.3 px per dp, at or above every phone's
 * density. Lossless WebP.
 *
 * --check does not re-draw (the T814 lesson, `build-coho.mjs`: the drawing is floating point, the Mac and CI's Linux were
 * never compared). It reads the COMMITTED files back (`fish-loader/sheet_facts.py`) and holds them to the tokens and the
 * module: each file's size, its two commonest colours (the ink, then the red), and the ring's colour present.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const PY = here("../../.venv/bin/python");
const DRAW = here("./fish-loader/adipose_art.py");
const FACTS = here("./fish-loader/sheet_facts.py");
const DIR = here("../packages/ui-native/src/adipose/");
const MODULE = here("../packages/ui-native/src/adipose.generated.ts");
const META = here("../packages/map/style/style.meta.json");

export const WIDTH = 1200, HEIGHT = 600;
const VARIANTS = ["wild", "clipped"];
/** the fewest pixels of exactly the ring's colour a drawing must hold (the ring's solid core: ~550 at 1200 px) */
const RING_MIN = 200;

const check = process.argv.includes("--check");
if (!existsSync(PY)) throw new Error(`build-adipose: no Python at ${PY} — make the repo's .venv (pip install -r requirements.txt -c constraints.txt)`);

const themes = JSON.parse(readFileSync(META, "utf8")).themes;
const names = Object.keys(themes).sort((a, b) => (a === "light" ? -1 : b === "light" ? 1 : a.localeCompare(b)));
const trioOf = (t) => {
  const v = (k) => {
    const x = themes[t][k];
    if (!x) throw new Error(`build-adipose: theme ${t} has no ${k} (pnpm style:build)`);
    return x.toUpperCase();
  };
  return { ink: v("color.ui.coho.ink"), red: v("color.ui.coho.red"), ring: v("color.ui.accent") };
};
/** drawing name -> its trio; theme -> its drawing name */
const sets = new Map();
const setOf = {};
for (const t of names) {
  const p = trioOf(t);
  const found = [...sets].find(([, q]) => q.ink === p.ink && q.red === p.red && q.ring === p.ring);
  const name = found ? found[0] : `adipose-${t}`;
  if (!found) sets.set(name, p);
  setOf[t] = name;
}
const file = (n, v) => `${n}-${v}.webp`;
const ident = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());

const moduleText = `/// <reference path="./assets.d.ts" />
/**
 * GENERATED by \`pnpm adipose:build\` (tools/build-adipose.mjs) from tools/fish-loader/adipose_art.py. Do not edit.
 *
 * (T886) The "Hatchery or wild?" sheet's two drawings, on the loader's coho: the wild fish with its adipose fin, the
 * clipped one with a healed scar, the spot ringed. ${WIDTH} x ${HEIGHT} px, lossless WebP, one pair per distinct
 * \`color.ui.coho.ink\` + \`.red\` + \`color.ui.accent\`, printed in those colours (never tinted); \`art\` names each theme's.
 */
${[...sets.keys()].flatMap((n) => VARIANTS.map((v) => `import ${ident(`${n}-${v}`)} from "./adipose/${file(n, v)}";`)).join("\n")}

export const ADIPOSE = {
  /** Each drawing, in px: the box \`AdiposeArt\` draws keeps this aspect. */
  size: { width: ${WIDTH}, height: ${HEIGHT} },
  /** Each theme's pair. */
  art: {
${[...names].sort().map((t) => `    ${t}: { wild: ${ident(`${setOf[t]}-wild`)}, clipped: ${ident(`${setOf[t]}-clipped`)} },`).join("\n")}
  },
} as const;
`;

const py = (args) => execFileSync(PY, ["-I", ...args], { encoding: "utf8" }).trim();

if (check) {
  const bad = [];
  if (!existsSync(MODULE) || readFileSync(MODULE, "utf8") !== moduleText) bad.push(`${MODULE} differs from what the tokens make`);
  const all = [...sets].flatMap(([n, trio]) => VARIANTS.map((v) => [join(DIR, file(n, v)), trio]));
  const missing = all.filter(([f]) => !existsSync(f));
  for (const [f] of missing) bad.push(`no drawing ${f}`);
  const known = new Set(all.map(([f]) => f.split("/").pop()));
  for (const f of existsSync(DIR) ? readdirSync(DIR) : []) if (!known.has(f)) bad.push(`a drawing no theme wears: ${f}`);
  if (!missing.length) {
    const facts = py([FACTS, ...all.map(([f]) => f)]).split("\n").map((l) => JSON.parse(l));
    for (const [i, got] of facts.entries()) {
      const [f, want] = all[i];
      const ring = JSON.parse(py([FACTS, "--counts", f, want.ring]))[want.ring];
      const ok = got.format === "WEBP" && got.width === WIDTH && got.height === HEIGHT &&
        got.colours[0] === want.ink && got.colours[1] === want.red && ring >= RING_MIN;
      if (!ok) bad.push(`${f}: ${JSON.stringify(got)}, ring ${ring} px; wanted ${WIDTH}x${HEIGHT} WEBP in ${want.ink} + ${want.red}, ring ${want.ring} >= ${RING_MIN} px`);
    }
  }
  if (bad.length) {
    console.error(`adipose: ${bad.length} problem(s) — run \`pnpm adipose:build\`\n  ${bad.join("\n  ")}`);
    process.exit(1);
  }
  console.log(`adipose: ${sets.size} pair(s) match the tokens (${names.map((t) => `${t} -> ${setOf[t]}`).join(", ")})`);
} else {
  mkdirSync(DIR, { recursive: true });
  for (const [n, { ink, red, ring }] of sets) {
    py([DRAW, "--ink", ink, "--red", red, "--ring", ring, "--width", String(WIDTH),
      "--wild", join(DIR, file(n, "wild")), "--clipped", join(DIR, file(n, "clipped"))]);
  }
  const keep = new Set([...sets.keys()].flatMap((n) => VARIANTS.map((v) => file(n, v))));
  for (const f of readdirSync(DIR)) if (!keep.has(f)) unlinkSync(join(DIR, f));
  writeFileSync(MODULE, moduleText);
  console.log(`adipose: ${[...keep].map((f) => `${f} ${(readFileSync(join(DIR, f)).length / 1024).toFixed(0)} KB`).join(", ")}`);
}
