/**
 * (T732) Android's backup rules (`apps/mobile/plugins/with-backup-rules.js`): the files written are pinned WHOLE, so a
 * path that slips in (the release, a cache) or out (the spots) fails here, not on a reader's new phone.
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";

// @ts-expect-error -- plain CommonJS run by `expo prebuild` (no types)
import { dataExtractionRules, fullBackupContent, setManifest } from "../apps/mobile/plugins/with-backup-rules.js";

const app = (attrs: Record<string, string>) => ({ manifest: { application: [{ $: { "android:name": ".MainApplication", ...attrs } }] } });

describe("with-backup-rules", () => {
  it("Android 11 and lower: the spots and the settings, nothing else", () => {
    expect(fullBackupContent()).toBe(`<?xml version="1.0" encoding="utf-8"?>
<!-- (T732) generated by plugins/with-backup-rules.js: an include list, so nothing else is backed up -->
<full-backup-content>
  <include domain="file" path="spots/spots.spots"/>
  <include domain="file" path="spots/spots.spots.bak"/>
  <include domain="file" path="spots/layers.json"/>
  <include domain="file" path="spots/notify.json"/>
  <include domain="file" path="spots/low-data.txt"/>
  <include domain="file" path="spots/crash-reports.txt"/>
  <include domain="file" path="spots/run-species.json"/>
  <include domain="file" path="spots/first-run.txt"/>
  <include domain="file" path="spots/walkthrough.txt"/>
</full-backup-content>
`);
  });

  it("Android 12+: the cloud gets the same list; a transfer to a new phone adds the photos", () => {
    expect(dataExtractionRules()).toBe(`<?xml version="1.0" encoding="utf-8"?>
<!-- (T732) generated by plugins/with-backup-rules.js: include lists, so nothing else is backed up or transferred -->
<data-extraction-rules>
  <cloud-backup>
    <include domain="file" path="spots/spots.spots"/>
    <include domain="file" path="spots/spots.spots.bak"/>
    <include domain="file" path="spots/layers.json"/>
    <include domain="file" path="spots/notify.json"/>
    <include domain="file" path="spots/low-data.txt"/>
    <include domain="file" path="spots/crash-reports.txt"/>
    <include domain="file" path="spots/run-species.json"/>
    <include domain="file" path="spots/first-run.txt"/>
    <include domain="file" path="spots/walkthrough.txt"/>
  </cloud-backup>
  <device-transfer>
    <include domain="file" path="spots/spots.spots"/>
    <include domain="file" path="spots/spots.spots.bak"/>
    <include domain="file" path="spots/layers.json"/>
    <include domain="file" path="spots/notify.json"/>
    <include domain="file" path="spots/low-data.txt"/>
    <include domain="file" path="spots/crash-reports.txt"/>
    <include domain="file" path="spots/run-species.json"/>
    <include domain="file" path="spots/first-run.txt"/>
    <include domain="file" path="spots/walkthrough.txt"/>
    <include domain="file" path="spots/photos"/>
  </device-transfer>
</data-extraction-rules>
`);
  });

  it("names both rule files on the application", () => {
    const m = setManifest(app({ "android:allowBackup": "true" }));
    expect(m.manifest.application[0].$).toEqual({
      "android:name": ".MainApplication", "android:allowBackup": "true",
      "android:fullBackupContent": "@xml/backup_rules", "android:dataExtractionRules": "@xml/data_extraction_rules",
    });
  });

  it("refuses a manifest whose backup rules someone else set, and one with backup off", () => {
    expect(() => setManifest(app({ "android:dataExtractionRules": "@xml/other" }))).toThrow(
      'with-backup-rules: the manifest already sets android:dataExtractionRules="@xml/other"; one owner of the backup rules (T732)');
    expect(() => setManifest(app({ "android:allowBackup": "false" }))).toThrow(
      "with-backup-rules: android:allowBackup is false, so no rule would ever run (T732)");
  });

  it("is in app.json's plugin list", () => {
    const plugins = JSON.parse(readFileSync(resolve(process.cwd(), "apps/mobile/app.json"), "utf8")).expo.plugins;
    expect(plugins).toContain("./plugins/with-backup-rules");
  });
});
