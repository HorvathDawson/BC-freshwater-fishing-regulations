#!/usr/bin/env node
/**
 * T405 — THE FISH THUMBNAILS, MADE FROM THE FISH PICTURES.
 *
 *   node tools/emit-fish-thumbs.mjs            -> writes apps/mobile/assets/fish/thumbs/<file> + thumbs.json
 *
 * A water page drew every row's fish (about 40-80 px wide) from the full 800 px picture: 30-72 kB each, ~400 kB of a
 * page's first view (T405). Each coded manifest picture gets a thumbnail THUMB_WIDTH px wide (3x the widest row picture,
 * GroupCard's 80 px), its own proportions kept, an RGBA WebP like the pictures (no ground behind a fish, D4). Rows and
 * chips draw the thumbnail; only the fish sheet's picture (`FishImage`, opened by a tap) draws the full one.
 *
 * Rasterised in headless Chrome (tools/regs-web/cdp.mjs, as emit-adipose.mjs): the picture decoded, drawn onto a canvas
 * with high-quality smoothing, read back as WebP. `thumbs.json` records, per picture, the sha256 of the picture it was
 * made from and of the thumbnail: `node tools/emit-fish.mjs --check` (`pnpm fish`, in `pnpm check`) refuses a picture
 * with no thumbnail, a thumbnail made from another version of its picture, or a thumbnail file that is not the one
 * recorded — so a new or changed picture fails the check until this is rerun. Never hand-made.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

const app = fileURLToPath(new URL("..", import.meta.url));
export const FISH_DIR = `${app}apps/mobile/assets/fish/`;
export const THUMB_DIR = `${FISH_DIR}thumbs/`;
export const THUMBS_RECORD = `${THUMB_DIR}thumbs.json`;
/** 3x the widest place a row draws a fish (GroupCard `Pictures`: 80 px), so a 3x phone screen gets its own pixels. */
export const THUMB_WIDTH = 240;
/** Chrome's WebP encoder quality: at 240 px the photos and plates stay clean at a few kB. */
const QUALITY = 0.82;

const sha = (b) => createHash("sha256").update(b).digest("hex");

/** The pictures that get a thumbnail: every manifest row with a species code (the hatch drawings, code null, do not). */
export function thumbFiles(manifest) {
  return [...new Set(manifest.images.filter((i) => i.code !== null && i.code !== undefined).map((i) => i.file))].sort();
}

/** A thumbnail's size for a picture of `width` x `height`. */
export const thumbSize = (width, height) => ({ width: THUMB_WIDTH, height: Math.round((THUMB_WIDTH * height) / width) });

async function main() {
  const manifest = JSON.parse(readFileSync(`${FISH_DIR}manifest.json`, "utf8"));
  const files = thumbFiles(manifest);
  const { open } = await import(pathToFileURL(`${app}tools/regs-web/cdp.mjs`).href);
  const chrome = await open(pathToFileURL(`${FISH_DIR}manifest.json`).href, { width: 400, height: 300 });
  const record = {};
  try {
    rmSync(THUMB_DIR, { recursive: true, force: true });
    mkdirSync(THUMB_DIR, { recursive: true });
    for (const file of files) {
      const img = manifest.images.find((i) => i.file === file);
      const src = readFileSync(`${FISH_DIR}${file}`);
      const { width, height } = thumbSize(img.width, img.height);
      const b64 = await chrome.evaluate(`(async () => {
        const img = new Image();
        img.src = "data:image/webp;base64,${src.toString("base64")}";
        await img.decode();
        if (img.naturalWidth !== ${img.width} || img.naturalHeight !== ${img.height}) throw new Error("size " + img.naturalWidth + "x" + img.naturalHeight);
        const c = document.createElement("canvas"); c.width = ${width}; c.height = ${height};
        const g = c.getContext("2d"); g.imageSmoothingEnabled = true; g.imageSmoothingQuality = "high";
        g.drawImage(img, 0, 0, ${width}, ${height});
        return c.toDataURL("image/webp", ${QUALITY}).split(",")[1];
      })()`);
      const out = Buffer.from(b64, "base64");
      if (out.toString("ascii", 8, 12) !== "WEBP") throw new Error(`emit-fish-thumbs: Chrome did not encode ${file} as WebP`);
      writeFileSync(`${THUMB_DIR}${file}`, out);
      record[file] = { source_sha256: sha(src), sha256: sha(out), width, height, bytes: out.length };
      console.log(`${file}  ${src.length} B -> ${out.length} B`);
    }
  } finally {
    await chrome.close();
  }
  const extra = readdirSync(THUMB_DIR).filter((f) => f.endsWith(".webp") && !(f in record));
  if (extra.length) throw new Error(`emit-fish-thumbs: unexpected files ${extra.join(", ")}`);
  writeFileSync(THUMBS_RECORD, `${JSON.stringify({
    _about: "GENERATED by app/tools/emit-fish-thumbs.mjs from the fish pictures (T405). Do not edit; rerun the tool.",
    width: THUMB_WIDTH, thumbs: record,
  }, null, 1)}\n`);
  const total = Object.values(record).reduce((n, r) => n + r.bytes, 0);
  console.log(`wrote ${files.length} thumbnails (${total} B) + ${THUMBS_RECORD}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
