"""T487: THE GAUGE SHARE CARD'S LETTERS, drawn once from the app's own face (Archivo) into alpha bitmaps.

    .venv/bin/python app/workers/feeds/tools/card_glyphs.py

writes app/workers/feeds/src/gauges/card/glyphs.generated.ts. The feeds worker draws each gauge's card (a small PNG,
src/gauges/card/) during the gauge run; it has no font engine, so every letter it can draw is here, already rasterised
by FreeType (Pillow) at the sizes the card uses. No kerning (a card line is short); advances are FreeType's.
Each face's bitmaps are one zlib stream (base64): the worker inflates a face the first time a card asks for it.
The TTFs' sha256 ride along; test/cards.test.ts refuses a generated file whose fonts no longer match the app's.
"""
from __future__ import annotations

import base64
import hashlib
import json
import zlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
APP = HERE.parents[2]
FONTS = APP / "node_modules/@expo-google-fonts/archivo"
OUT = HERE.parent / "src/gauges/card/glyphs.generated.ts"

TEXT = "".join(chr(c) for c in range(32, 127)) + "³°·–—‘’“”…→×éÉèàâçôîïüñ"
DIGITS = "0123456789.,-–m³/s %"
# face key -> (weight file, pixel size, the characters drawn)
FACES = {
    "small": ("400Regular/Archivo_400Regular.ttf", 26, TEXT),
    "body": ("400Regular/Archivo_400Regular.ttf", 34, TEXT),
    "title": ("700Bold/Archivo_700Bold.ttf", 58, TEXT),
    "big": ("700Bold/Archivo_700Bold.ttf", 104, DIGITS),
}


def face(rel: str, size: int, chars: str) -> dict:
    chars = "".join(dict.fromkeys(chars))
    font = ImageFont.truetype(str(FONTS / rel), size)
    ascent, descent = font.getmetrics()
    adv, box, blobs = [], [], bytearray()
    for ch in chars:
        adv.append(round(font.getlength(ch) * 4) / 4)
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            data = img.tobytes()
        else:
            data = b""
        box.append([l, t, w, h, len(blobs)])
        blobs += data
    return {"size": size, "ascent": ascent, "descent": descent, "chars": chars, "adv": adv, "box": box,
            "data": base64.b64encode(zlib.compress(bytes(blobs), 9)).decode()}


def main() -> None:
    sha = {rel: hashlib.sha256((FONTS / rel).read_bytes()).hexdigest() for rel, _, _ in FACES.values()}
    faces = {k: face(*v) for k, v in FACES.items()}
    body = (
        "// generated by app/workers/feeds/tools/card_glyphs.py (T487) from Archivo — do not edit; rerun it.\n"
        "/* eslint-disable */\n"
        "export interface GlyphFace {\n"
        "  readonly size: number; readonly ascent: number; readonly descent: number; readonly chars: string;\n"
        "  /** advance per char (px) */ readonly adv: readonly number[];\n"
        "  /** per char [left, top (from the baseline, up is negative), width, height, offset into the bitmaps] */\n"
        "  readonly box: readonly (readonly [number, number, number, number, number])[];\n"
        "  /** the alpha bitmaps, one zlib stream, base64 */ readonly data: string;\n"
        "}\n"
        f"export const FONT_SHA256: Readonly<Record<string, string>> = {json.dumps(sha, indent=1)};\n"
        f"export const FACES = {json.dumps(faces, ensure_ascii=False, separators=(',', ':'))} as const satisfies Record<string, GlyphFace>;\n"
        "export type FaceKey = keyof typeof FACES;\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding="utf-8")
    print(f"{OUT}: {len(body)} bytes, faces {', '.join(f'{k} {v[1]}px' for k, v in FACES.items())}")


if __name__ == "__main__":
    main()
