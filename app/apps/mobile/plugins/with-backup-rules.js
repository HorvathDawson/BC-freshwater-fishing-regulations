/**
 * (T732) WHAT ANDROID'S BACKUP CARRIES: the reader's spots first, never the downloaded release. Applied by `expo prebuild`
 * (android/ is generated, never edited).
 *
 * WHY. With no rules, Auto Backup takes the whole files folder, the databases, the shared preferences and the external
 * files folder. The installed release (~480 MB: data, synopsis, atlas, basemap) sits in the files folder beside the spots,
 * and Android skips the WHOLE cloud backup when an app's data passes its 25 MB quota, so the spots were never saved.
 *
 * THE RULES ARE AN INCLUDE LIST. Once a rule file has one <include>, Android backs up only what is named, so every file
 * not listed below stays out by construction: the release (`release/`), the synopsis PDF (`synopsis-*.pdf`), MapLibre's
 * tile cache, the feed and forecast captures, the update service's state (its validators would claim a release the new
 * phone does not have), the background-download jobs (shared preferences and the external folder name another device's
 * DownloadManager ids), WorkManager's database, logs, crash records and the install id (a new phone is a new install).
 *
 *   cloud backup (25 MB quota)   the spots file (+ its `.bak`) and the small settings the reader would miss.
 *                                NO PHOTOS: a phone's photos pass 25 MB within a few dozen, and an over-quota set backs
 *                                up nothing, spots included. Photos go through the T732 backup set when it is built.
 *   device-to-device transfer    the same, PLUS the photos as kept (no quota on a cable or Wi-Fi transfer to a new phone).
 *   Android 11 and lower         `fullBackupContent` is the cloud list only: its `requireFlags="deviceToDeviceTransfer"`
 *                                gate is Android 9+, and an ungated photo include on Android 7–8 would risk the quota.
 *
 * A manifest that already names backup rules (another plugin, a template change) is refused here, at prebuild: two
 * owners of the backup rules is the silent-loss case this file exists to prevent.
 */
const fs = require("node:fs");
const path = require("node:path");
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require("expo/config-plugins");

/** Paths under the app's files folder (expo-file-system `Paths.document` = Context.getFilesDir()). */
const SPOTS = ["spots/spots.spots", "spots/spots.spots.bak"];
/** The reader's settings (`packages/data/src/spots/store.native.ts`): small files the reader would miss on a new phone. */
const SETTINGS = [
  "spots/layers.json",          // the Layers sheet's switches
  "spots/notify.json",          // notification settings and gauge alert rules
  "spots/low-data.txt",         // the Data setting
  "spots/crash-reports.txt",    // the "Send crash reports" switch: a consent the reader gave
  "spots/run-species.json",     // the species the Runs tab paints
  "spots/first-run.txt",        // the first-run notice already accepted (a version bump re-asks)
  "spots/walkthrough.txt",      // the walkthrough already seen
];
/** The photos as kept (`photoStore.native.ts`): device-to-device transfer only. */
const PHOTOS = "spots/photos";

const CLOUD = [...SPOTS, ...SETTINGS];
const DEVICE = [...CLOUD, PHOTOS];

const includes = (paths, indent) => paths.map((p) => `${indent}<include domain="file" path="${p}"/>`).join("\n");

/** res/xml/backup_rules.xml: Android 6–11 (`android:fullBackupContent`), cloud and transfer alike. */
function fullBackupContent() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- (T732) generated by plugins/with-backup-rules.js: an include list, so nothing else is backed up -->
<full-backup-content>
${includes(CLOUD, "  ")}
</full-backup-content>
`;
}

/** res/xml/data_extraction_rules.xml: Android 12+ (`android:dataExtractionRules`). */
function dataExtractionRules() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- (T732) generated by plugins/with-backup-rules.js: include lists, so nothing else is backed up or transferred -->
<data-extraction-rules>
  <cloud-backup>
${includes(CLOUD, "    ")}
  </cloud-backup>
  <device-transfer>
${includes(DEVICE, "    ")}
  </device-transfer>
</data-extraction-rules>
`;
}

const FULL = "android:fullBackupContent", EXTRACT = "android:dataExtractionRules";

/** Point the <application> at the two rule files; refuse a manifest that already names other rules. */
function setManifest(manifest) {
  const app = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
  for (const [key, value] of [[FULL, "@xml/backup_rules"], [EXTRACT, "@xml/data_extraction_rules"]]) {
    const had = app.$[key];
    if (had !== undefined && had !== value) {
      throw new Error(`with-backup-rules: the manifest already sets ${key}="${had}"; one owner of the backup rules (T732)`);
    }
    app.$[key] = value;
  }
  if (app.$["android:allowBackup"] === "false") {
    throw new Error("with-backup-rules: android:allowBackup is false, so no rule would ever run (T732)");
  }
  return manifest;
}

module.exports = function withBackupRules(config) {
  config = withAndroidManifest(config, (c) => { c.modResults = setManifest(c.modResults); return c; });
  return withDangerousMod(config, ["android", (c) => {
    const dir = path.join(c.modRequest.platformProjectRoot, "app/src/main/res/xml");
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "backup_rules.xml"), fullBackupContent());
    fs.writeFileSync(path.join(dir, "data_extraction_rules.xml"), dataExtractionRules());
    return c;
  }]);
};
module.exports.fullBackupContent = fullBackupContent;
module.exports.dataExtractionRules = dataExtractionRules;
module.exports.setManifest = setManifest;
