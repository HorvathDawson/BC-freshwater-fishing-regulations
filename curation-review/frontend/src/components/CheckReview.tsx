/* THE CHECKLIST (T532, owner 2026-11-09 on the round-4 mockup): one place at a time — a big map with the extent in
   ONE colour (a save not drawn yet dashed) and a numbered pin per row; the rows are the CLAIMS the place makes,
   generated by the server (`review.checklist`): the source's phrase → what ours does → ✓ / ? / ✗. One decision:
   "All correct" (every row ✓ or ticked) or "Something's wrong" (pick the rows, a note) — each a mark. A change of
   extent is the T525 editor, reached from "Something's wrong" (every guard R1–R7 is its own). The queue is BY WATER
   (owner 2026-11-09: "review a whole river or waterbody at one time"): a water's places come together, its map stays
   loaded while stepping through them, progress is said per water and overall. */

export type CheckSource = "dfo" | "regs" | "all";
const FILTERS: [string, string][] = [["", "all"], ["todo", "unchecked"], ["bad", "has ✗"], ["unsure", "has ?"]];
const KIND_WORDS: Record<string, string> = { unchecked: "words" };
const hashOf = (source: CheckSource) => (source === "dfo" ? "dfo/" : "checks/");

interface Loaded {
  id: string; place: CheckPlace; check: PlaceCheck;
  /** the map: the place's waters, the extent now, a save not drawn yet */
  items: { id: string; name: string }[]; reach: GeoJSON.FeatureCollection | null; pending: GeoJSON.FeatureCollection | null;
  title: string; sub: string; words: string; pageUrl?: string | null;
  dfo?: DfoDetail; entry?: EntryDetail;
}

export function CheckReview({ mode, source: initial }: { mode: Mode; source: CheckSource }) {
  const [source, setSource] = useState<CheckSource>(initial);
  const [filter, setFilter] = useState("");
  const [q, setQ] = useState("");
  const [queue, setQueue] = useState<CheckPlace[] | null>(null);
  const [progress, setProgress] = useState<CheckProgress | null>(null);
  const [dfoProgress, setDfoProgress] = useState<DfoProgress | null>(null);
  const [error, setError] = useState("");
  const prefix = hashOf(initial);
  const [selected, setSelected] = useState<string | null>(() => {
    const h = decodeURIComponent(window.location.hash.slice(1));
    return h.startsWith(prefix) ? h.slice(prefix.length) || null : null;
  });
  const [loaded, setLoaded] = useState<Loaded | null>(null);
  const [editing, setEditing] = useState(false);
  const [version, setVersion] = useState(0);

  const loadQueue = useCallback(() => {
    api.checksQueue(source, filter, q).then(setQueue).catch((e) => setError(`the checklist queue: ${e}`));
    api.checksProgress(source).then(setProgress).catch((e) => setError(`the checklist progress: ${e}`));
    if (source !== "regs") api.dfoProgress().then(setDfoProgress).catch(failed("the DFO vintage check"));
  }, [source, filter, q]);
  useEffect(() => { loadQueue(); }, [loadQueue]);

  const open = useCallback((id: string) => {
    setSelected(id);
    setEditing(false);
    window.history.replaceState(null, "", `#${prefix}${encodeURIComponent(id)}`);
  }, [prefix]);
  useEffect(() => {
    const onHash = () => {
      const h = decodeURIComponent(window.location.hash.slice(1));
      if (h.startsWith(prefix) && h.length > prefix.length) setSelected(h.slice(prefix.length));
    };
    window.addEventListener("hashchange", onHash);
    return () => window.removeEventListener("hashchange", onHash);
  }, [prefix]);
  // the first place of the list when the URL names none
  useEffect(() => { if (!selected && queue?.length) open(queue[0].id); }, [queue, selected, open]);

  const place = useMemo(() => queue?.find((p) => p.id === selected) ?? null, [queue, selected]);
  useEffect(() => {
    if (!selected) return;
    let live = true;
    const id = selected;
    loadPlace(id, place).then((got) => { if (live) setLoaded(got); })
      .catch((e) => live && setError(`${id}: ${e}`));
    return () => { live = false; };
  }, [selected, version]);  // eslint-disable-line react-hooks/exhaustive-deps

  const nav = useRef({ next: null as string | null, prev: null as string | null });
  const list = queue ?? [];
  nav.current = { next: step(list, selected, 1), prev: selected ? step(list, selected, -1) : null };
  useEffect(() => {
    const onKey = (ev: KeyboardEvent) => {
      if (isTyping(ev.target) || ev.metaKey || ev.ctrlKey || ev.altKey) return;
      if ((ev.key === "j" || ev.key === "ArrowRight") && nav.current.next) { open(nav.current.next); ev.preventDefault(); }
      else if ((ev.key === "k" || ev.key === "ArrowLeft") && nav.current.prev) { open(nav.current.prev); ev.preventDefault(); }
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open]);

  const at = where(list, selected);
  const water = place && progress?.waters[place.water_key];
  const waters = useMemo(() => {
    const seen = new Map<string, CheckPlace>();
    for (const p of list) if (!seen.has(p.water_key)) seen.set(p.water_key, p);
    return [...seen.values()];
  }, [list]);
  const cur = loaded && loaded.id === selected ? loaded : null;

  const header = (
    <header className="ck-head">
      <h1 data-testid="ck-title">{cur?.title ?? place?.water ?? "…"}<small>{cur?.sub ?? ""}</small></h1>
      <span className="ck-progress" data-testid="ck-progress">
        {progress ? <><b>{progress.done}</b> of {progress.total} checked</> : "…"}
        {water && <span data-testid="ck-water-progress"> · {water.water}: {water.done} of {water.total}</span>}
      </span>
      <div className="ck-nav">
        <button aria-label="Previous place" disabled={!nav.current.prev} onClick={() => nav.current.prev && open(nav.current.prev)}>‹</button>
        <span data-testid="ck-pos">{at.pos || "–"} of {at.total}</span>
        <button aria-label="Next place" disabled={!nav.current.next} onClick={() => nav.current.next && open(nav.current.next)}>›</button>
      </div>
    </header>
  );

  return (
    <div className="app ck-mode" data-testid="ck-mode">
      <TopNav active={initial === "dfo" ? "dfo" : "entries"} sub={initial === "dfo" ? "extents" : "checks"} />
      {header}
      <div className="ck-bar">
        {initial !== "dfo" && (
          <span className="ck-chips" role="tablist" aria-label="which extents">
            {(["all", "regs", "dfo"] as CheckSource[]).map((s) => (
              <button key={s} role="tab" aria-selected={source === s} onClick={() => setSource(s)}>
                {s === "all" ? "both" : s === "regs" ? "regulations" : "DFO"}</button>))}
          </span>
        )}
        <span className="ck-chips" role="tablist" aria-label="filter">
          {FILTERS.map(([k, w]) => (
            <button key={k} role="tab" aria-selected={filter === k} data-testid={`ck-filter-${k || "all"}`}
              onClick={() => setFilter(k)}>{w}
              {progress && k === "todo" ? ` ${(progress.by_check.unchecked ?? 0) + (progress.by_check.stale ?? 0)}`
                : progress && k === "bad" ? ` ${progress.by_worst.bad ?? 0}` : progress && k === "unsure" ? ` ${progress.by_worst.unsure ?? 0}` : ""}
            </button>))}
        </span>
        <select aria-label="jump to a water" data-testid="ck-water" value={place?.water_key ?? ""}
          onChange={(e) => { const p = list.find((x) => x.water_key === e.target.value); if (p) open(p.id); }}>
          {waters.map((p) => <option key={p.water_key} value={p.water_key}>{p.water} · r{p.region}</option>)}
        </select>
        <input type="search" placeholder="find a water or words…" value={q} aria-label="find" onChange={(e) => setQ(e.target.value)} />
        <span className="dim">{queue ? `${list.length} places on ${waters.length} waters` : "loading…"}</span>
      </div>
      {dfoProgress && <DfoVintageBanner notes={dfoProgress.vintage} />}
      <InputsSyncLine reason="write-through" />
      {error && <div className="errors inline-notice" style={{ margin: "2px 8px", padding: "2px 8px" }}>
        <span style={{ flex: 1 }}>{error}</span><CloseX onClick={() => setError("")} /></div>}
      {editing && cur?.dfo ? (
        <div className="main">
          <DfoLocation key={`${cur.id}|${version}`} detail={cur.dfo} mode={mode} initialCall="change"
            nav={{ pos: at.pos, total: at.total }} saving={false}
            onBack={() => setEditing(false)}
            onMarked={() => { setEditing(false); loadQueue(); setVersion((v) => v + 1); }} />
        </div>
      ) : (
        <main className="ck-main">
          <div className="ck-map">
            {/* ONE MAP PER WATER: keyed by the water, so stepping its places changes rows and pins, never the map */}
            {cur ? <CheckMap key={cur.place.water_key} loaded={cur} /> : <div className="empty-state">loading…</div>}
          </div>
          {cur ? <CheckPanel key={`${cur.id}|${cur.check.digest}`} loaded={cur}
            onSaved={() => { loadQueue(); setVersion((v) => v + 1); }}
            onChange={cur.dfo && !cur.dfo.extent_now.cannot_change.length ? () => setEditing(true) : undefined} />
            : <aside className="ck-side"><div className="empty-state">{queue && !list.length ? "Nothing matches." : "loading…"}</div></aside>}
        </main>
      )}
    </div>
  );
}

/** everything one place shows: its rows, and the map's layers */
async function loadPlace(id: string, place: CheckPlace | null): Promise<Loaded> {
  const isRule = place ? place.source === "regs" : id.includes("#");
  if (!isRule) {
    const [check, d] = await Promise.all([api.checkDfo(id), api.dfoLocation(id)]);
    const reach = await api.dfoReach(id, false).catch((e) => { failed("the DFO reach")(e); return null; });
    let pending: GeoJSON.FeatureCollection | null = null;
    const saved = d.saved && d.saved.state !== "landed" && d.saved.state !== "deferred" ? savedFixesOf(d.mark) : null;
    if (saved?.length) {
      const pv = await api.dfoExtentPreview(id, saved as ExtentFix[], false).catch(() => null);
      if (pv?.resolvable) pending = (pv.geojson ?? null) as GeoJSON.FeatureCollection | null;
    }
    const p: CheckPlace = place ?? { source: "dfo", id, water: d.row.water, water_key: d.items.map((i) => i.id).sort().join("|"),
      region: d.row.region, text: d.row.text, summary: check.summary, check: check.check };
    return { id, place: p, check, dfo: d, items: d.items.map((i) => ({ id: i.id, name: i.name })),
             reach: reach?.resolvable ? (reach.geojson as GeoJSON.FeatureCollection) : null, pending,
             title: d.verbatim.waters || d.row.water, sub: `DFO region ${d.row.region}${d.row.status !== "active" ? " · no longer on the live page" : ""}`,
             words: d.verbatim.specific_area || "(no area given: the whole water)", pageUrl: d.page_url };
  }
  const [entryId, ruleId] = id.split("#");
  const [check, e] = await Promise.all([api.checkRule(entryId, ruleId), api.entry(entryId)]);
  const rr = await api.ruleResolved(entryId, ruleId).catch((x) => { failed("the rule's reach")(x); return null; });
  const items = [...(e.item ? [{ id: e.item.id, name: e.item.name }] : []), ...(e.also_items ?? []).map((a) => ({ id: a.id, name: a.name }))];
  const p: CheckPlace = place ?? { source: "regs", id, water: check.source?.name ?? entryId, water_key: items.map((i) => i.id).sort().join("|"),
    region: check.source?.region ?? "", text: check.source?.verbatim ?? "", summary: check.summary, check: check.check,
    entry_id: entryId, rule_id: ruleId };
  return { id, place: p, check, entry: e, items, reach: (rr?.geojson ?? null) as unknown as GeoJSON.FeatureCollection | null,
           pending: null, title: check.source?.name ?? entryId,
           sub: `region ${check.source?.region ?? "?"} · ${ruleId}${check.source?.pages.length ? ` · p.${check.source.pages.join(", ")}` : ""}`,
           words: check.source?.verbatim ?? "" };
}

/** the water's map: the extent now in one colour, a save not drawn yet dashed, a numbered pin per row */
function CheckMap({ loaded }: { loaded: Loaded }) {
  const [on, setOn] = useState<number | null>(null);
  useEffect(() => {
    const h = (e: Event) => setOn((e as CustomEvent<number | null>).detail);
    window.addEventListener("ck-pin", h);
    return () => window.removeEventListener("ck-pin", h);
  }, []);
  const pins = useMemo(() => pinsFc(loaded.check.rows, on), [loaded.check.rows, on]);
  // the view fits the FIRST place opened on this water; stepping its other places keeps it (the map stays)
  const first = useRef(loaded.id);
  // the cuts the rows name, labelled (never every cut on the water: the rows are what is checked)
  const named = useMemo(() => {
    const want = new Set(loaded.check.rows.flatMap((r) => r.anchor.cuts ?? []));
    const fc = loaded.dfo?.splits;
    return fc ? { ...fc, features: fc.features.filter((f) => want.has(f.properties.split_id)) } : null;
  }, [loaded]);
  return (
    <>
      <div className="ck-key"><span><i />the extent now</span>
        {loaded.pending && <span><i className="dash" />saved, not drawn yet</span>}</div>
      <MapPanel itemId={loaded.items[0]?.id ?? null} alsoItemIds={loaded.items.slice(1).map((i) => i.id)}
        namedSplits={named} preview={loaded.reach} pending={loaded.pending} pins={pins} fitPreview={loaded.id === first.current}
        onPin={(n) => window.dispatchEvent(new CustomEvent("ck-pin-pick", { detail: n }))} />
    </>
  );
}

const pinTo = (n: number | null) => window.dispatchEvent(new CustomEvent("ck-pin", { detail: n }));

/** the rows and the one decision */
function CheckPanel({ loaded, onSaved, onChange }: { loaded: Loaded; onSaved: () => void; onChange?: () => void }) {
  const pc = loaded.check;
  const [ticked, setTicked] = useState<Set<number>>(() => new Set(
    (pc.check === "checked" ? pc.checked?.rows.filter((r) => r.ticked).map((r) => r.n) : []) ?? []));
  const [wrong, setWrong] = useState<Set<number>>(new Set());
  const [wrongMode, setWrongMode] = useState(false);
  const [note, setNote] = useState("");
  const [reviewer, setName] = useState(getReviewer);
  const [busy, setBusy] = useState(false);
  const [errors, setErrors] = useState<string[]>([]);
  const [picked, setPicked] = useState<number | null>(null);
  const since = useRef(Date.now());
  useEffect(() => {
    const h = (e: Event) => { const n = (e as CustomEvent<number>).detail; setPicked(n); pinTo(n);
      document.querySelector(`[data-row="${n}"]`)?.scrollIntoView({ block: "nearest" }); };
    window.addEventListener("ck-pin-pick", h);
    return () => { window.removeEventListener("ck-pin-pick", h); pinTo(null); };
  }, []);
  const key = loaded.dfo ? wtKey("dfo", loaded.id) : null;
  const [outcome, setOutcome] = useState(() => (key ? writeThrough().outcomes[key] ?? null : null));
  useEffect(() => (key ? onWriteThrough((s) => setOutcome(s.outcomes[key] ?? null)) : undefined), [key]);

  const left = openRows(pc.rows, ticked).length;
  const toggle = (set: Set<number>, n: number) => { const x = new Set(set); if (x.has(n)) x.delete(n); else x.add(n); return x; };

  async function save(call: "ok" | "wrong") {
    setErrors([]);
    if (!reviewer.trim()) { setErrors(["Type your name first: every mark names its reviewer."]); return; }
    if (call === "wrong" && !wrong.size) { setErrors(["Pick the row(s) that are wrong."]); return; }
    setReviewer(reviewer.trim());
    setBusy(true);
    try {
      const target = loaded.dfo ? { source: "dfo" as const, id: loaded.id, seen: loaded.dfo.extent_now.seen }
        : { source: "regs" as const, entry_id: loaded.place.entry_id ?? loaded.id.split("#")[0],
            rule_id: loaded.place.rule_id ?? loaded.id.split("#")[1] };
      await api.postMark(checkBody(target, pc, call, ticked, wrong, note,
        { reviewer: reviewer.trim(), seconds: Math.round((Date.now() - since.current) / 100) / 10 }));
      setWrongMode(false);
      onSaved();
    } catch (e) {
      const fe = (e as EntryRefused).fieldErrors;
      setErrors([`Refused: ${fe ? fe.map((x) => x.msg).join("; ") : String(e)}`]);
    } finally {
      setBusy(false);
    }
  }

  // the one status line: the check in force, then what the place's last extent save did (DFO)
  const d = loaded.dfo;
  const cutLabel = (c: string) => d?.cut_labels[c] ?? null;
  const itemName = (i: string) => d?.item_names[i] ?? loaded.items.find((x) => x.id === i)?.name ?? i;
  const ext = d?.location.binding.extents ?? [];
  const saved = d ? statusLine({ saved: d.saved, outcome, saving: false, stale: false,
    nowText: ext.length ? partsText(piecesParts(ext, (x) => extentParts(x, cutLabel, itemName))) : "",
    cutName: (c) => cutLabel(c) ?? c }) : null;
  const status = busy ? "Saving…" : checkStatus(pc);
  const extentNote = saved && d?.saved && d.saved.state !== "landed" ? saved.text : "";

  return (
    <aside className="ck-side" data-testid="ck-panel">
      <div className="ck-words">
        <span data-testid="ck-words">{loaded.words}</span>
        {loaded.pageUrl && <> · <a href={loaded.pageUrl} target="_blank" rel="noreferrer">DFO page ↗</a></>}
        <div className="dim">{pc.rows.length} claims</div>
      </div>
      <div className="ck-rows" data-testid="ck-rows" onMouseLeave={() => pinTo(picked)}>
        {pc.rows.map((r) => (
          <Row key={r.n} r={r} ticked={ticked.has(r.n)} wrong={wrong.has(r.n)} on={picked === r.n} wrongMode={wrongMode}
            onHover={() => pinTo(r.n)}
            onClick={() => { if (wrongMode) setWrong((w) => toggle(w, r.n)); else { setPicked(r.n); pinTo(r.n); } }}
            onTick={() => setTicked((t) => toggle(t, r.n))} />
        ))}
      </div>
      <div className="ck-foot">
        {!wrongMode ? (
          <>
            <div className="ck-btns">
              <button data-testid="ck-allok" disabled={left > 0 || busy || !!pc.held} onClick={() => void save("ok")}>All correct</button>
              <button className="alt" data-testid="ck-wrong" disabled={busy || !!pc.held} onClick={() => {
                setWrongMode(true); setWrong(new Set(openRows(pc.rows, ticked).map((r) => r.n))); }}>Something's wrong</button>
            </div>
            <div className="hint" data-testid="ck-hint">{pc.held ? <>Held: {pc.held}.{onChange && <> <button type="button"
              className="link" data-testid="ck-change-held" onClick={onChange}>Change the extent…</button></>}</>
              : hintWords(pc.rows, ticked)}</div>
          </>
        ) : (
          <div className="ck-wrongbox" data-testid="ck-wrongbox">
            <div className="hint">Tap the row(s) that are wrong{wrong.size ? ` (${[...wrong].sort((a, b) => a - b).join(", ")})` : ""}.</div>
            <input placeholder="note (optional)" value={note} onChange={(e) => setNote(e.target.value)} aria-label="note" />
            <div className="ck-btns">
              <button data-testid="ck-save-wrong" disabled={busy || !wrong.size} onClick={() => void save("wrong")}>Save: wrong rows</button>
              <button className="alt" onClick={() => { setWrongMode(false); setWrong(new Set()); }}>Cancel</button>
            </div>
            {onChange && <button type="button" className="btn small link" data-testid="ck-change"
              title="the extent editor, starting from the extent now; the save says what it replaces"
              onClick={onChange}>Change the extent instead…</button>}
          </div>
        )}
        {!getReviewer() && <input placeholder="your name" value={reviewer} aria-label="reviewer" onChange={(e) => setName(e.target.value)} />}
        {errors.length > 0 && <div className="errors" role="alert" data-testid="ck-errors" style={{ position: "static" }}>
          {errors.map((e, i) => <div key={i}>{e}</div>)}</div>}
        <div className="ck-status" role="status" data-testid="ck-status">
          <b>{status}</b>{extentNote ? <> · {extentNote}</> : null}
          {pc.checked?.note && pc.check !== "unchecked" ? <span className="dim"> · {pc.checked.note.slice(0, 160)}</span> : null}
        </div>
      </div>
    </aside>
  );
}

function Row({ r, ticked, wrong, on, wrongMode, onHover, onClick, onTick }: {
  r: CheckRow; ticked: boolean; wrong: boolean; on: boolean; wrongMode: boolean;
  onHover: () => void; onClick: () => void; onTick: () => void;
}) {
  const mark = r.state === "ok" || ticked ? "✓" : r.state === "bad" ? "✗" : "?";
  return (
    <div className={`ck-row ${r.state}${ticked ? " ticked" : ""}${wrong ? " wrongpick" : ""}${on ? " on" : ""}`}
      data-row={r.n} data-testid="ck-row" onMouseEnter={onHover} onClick={onClick}>
      <div className="n">{r.n}</div>
      <div>
        <div className="q"><b>{KIND_WORDS[r.kind] ?? r.kind}</b>{r.quote ? <q>{r.quote}</q> : <span className="dim">(no words for it)</span>}</div>
        <div className="ours">ours: <span>{r.ours}</span>{r.reason ? <> · {r.reason}</> : null}</div>
      </div>
      <button type="button" className="tick" disabled={r.state === "ok" || wrongMode} aria-pressed={ticked}
        title={r.state === "ok" ? "matches" : ticked ? "ticked: you checked it" : "tick it once you have checked it by eye"}
        data-testid="ck-tick" onClick={(e) => { e.stopPropagation(); onTick(); }}>{mark}</button>
    </div>
  );
}
