/* THE WATER'S PLACES, ALL IN SIGHT (owner 2026-11-09: "for a river show all historical boundaries too"). */

export type PlaceChip = "saved, waits build" | "saved, built" | "saved, not applied" | "done" | "verified earlier" | "reported wrong" | "needs extent" | "changed" | "has ✗" | "to check";
/** the one state chip of a place in the water's list */
export function chipOf(p: Pick<WaterPlace, "check" | "state" | "extents" | "bad">): PlaceChip {
  if (p.check === "checked") return "done";
  if (p.check === "unapplied") return "saved, not applied";
  if (p.check === "saved") return p.extents.length && p.state === "bound" ? "saved, built" : "saved, waits build";
  if (p.check === "earlier") return "verified earlier";
  if (p.check === "wrong") return "reported wrong";
  if (!p.extents.length || p.state === "unbound" || p.state === "needs_cut") return "needs extent";
  if (p.check === "stale") return "changed";
  return p.bad > 0 ? "has ✗" : "to check";
}
export const isDone = (p: { check: PlaceCheck["check"] }) =>
  p.check === "checked" || p.check === "earlier" || p.check === "saved" || p.check === "wrong";

/** THE LIST AS HE WANTS IT (owner 2026-11-10: "order them by easiest first and … hide the ones that are done"):
 *  `hideDone` drops done places (the one shown, `keep`, always stays); `easiest` puts the waters with the least work
 *  first — by the SUM of their not-done places' ease ranks, then by how many are left, then the list's own order — and
 *  within a water the easiest place first (done ones last). A water is never split: all its places stay together.
 *  -> the list, and how many done places were hidden. */
export function arrange(queue: CheckPlace[], o: { easiest: boolean; hideDone: boolean; keep?: string | null }):
    { list: CheckPlace[]; hidden: number } {
  const shown = o.hideDone ? queue.filter((p) => !isDone(p) || p.id === o.keep) : queue;
  const hidden = queue.length - shown.length;
  if (!o.easiest) return { list: shown, hidden };
  const rank = (p: CheckPlace) => (isDone(p) ? 99 : p.ease?.rank ?? 50);
  const waters = new Map<string, CheckPlace[]>();
  for (const p of shown) waters.set(p.water_key, [...(waters.get(p.water_key) ?? []), p]);
  const order = [...waters.keys()];
  const work = (k: string) => {
    const left = waters.get(k)!.filter((p) => !isDone(p));
    return { sum: left.reduce((n, p) => n + rank(p), 0), n: left.length };
  };
  const sorted = order.map((k, i) => ({ k, i, ...work(k) })).sort((a, b) =>
    (a.n === 0 ? 1 : 0) - (b.n === 0 ? 1 : 0) || a.sum - b.sum || a.n - b.n || a.i - b.i);
  return { list: sorted.flatMap(({ k }) => waters.get(k)!.map((p, i) => ({ p, i }))
    .sort((a, b) => rank(a.p) - rank(b.p) || a.i - b.i).map((x) => x.p)), hidden };
}

type ClosedArea = { name: string; metres: number | null; state?: string; kind?: string; radius_m?: number; note?: string;
                    ends: { label: string; new: boolean; coord?: [number, number] | null }[]; ring?: [number, number][];
                    line?: [number, number][]; live?: boolean; held?: string; confirmed?: boolean;
                    mark?: { verdict: string; date: string } | null };
const drawn = (a: ClosedArea) => a.state !== "not live";
/** ENTRY B ON THE MAP (T573): each closed STRETCH whose two ends are placed, as a pair to walk the river between — never
 *  one DFO's live page no longer names */
export function closedPairs(areas: ClosedArea[]): [[number, number], [number, number]][] {
  return areas.filter(drawn).flatMap((a) => (a.ends.length === 2 && a.ends[0].coord && a.ends[1].coord
    ? [[a.ends[0].coord, a.ends[1].coord] as [[number, number], [number, number]]] : []));
}
/** …and each closed CIRCLE as a polygon at true ground radius (the server's ring), same rule */
export function closedCircles(areas: ClosedArea[]): GeoJSON.FeatureCollection {
  // owner 2026-11-10 (Pinkut Creek): an item only an older wording names is drawn HERE ONLY, muted (`muted`: grey,
  // dashed), so it can be checked; a line across a lake placed by hand is drawn as its line
  const shapes = areas.filter((a) => a.ring && a.ring.length > 3).map((a) => ({
    type: "Feature" as const,
    properties: { name: drawn(a) ? a.name : `${a.name} (not live)`, flagged: a.state === "changed" || a.state === "radius", muted: !drawn(a) },
    geometry: { type: "Polygon" as const, coordinates: [a.ring!] } }));
  const lines = areas.filter((a) => a.line && a.line.length === 2).map((a) => ({
    type: "Feature" as const, properties: { name: a.name, flagged: false, muted: !drawn(a) },
    geometry: { type: "LineString" as const, coordinates: a.line! } }));
  return { type: "FeatureCollection", features: [...shapes, ...lines] };
}
/** WHERE ONE CLOSED AREA STANDS, in the owner's words: his confirm, his "wrong", or a proposal waiting for him */
export function areaStatus(a: ClosedArea): { words: string; tone: "done" | "wrong" | "todo" } {
  if (a.confirmed) return { words: `confirmed by you${a.mark?.date ? ` ${a.mark.date}` : ""}`, tone: "done" };
  if (a.mark?.verdict === "wrong") return { words: `you said something's wrong${a.mark.date ? ` ${a.mark.date}` : ""}`, tone: "wrong" };
  // his confirm is saved as a mark but the closed-areas file does not hold it (the write was refused, or is off)
  if (a.mark?.verdict === "verified") return { words: `your confirm is saved${a.mark.date ? ` (${a.mark.date})` : ""} but NOT in the closed-areas file yet`, tone: "wrong" };
  const placed = a.state === "not live" ? a.held !== "unplaced" : a.state !== "unplaced";
  return { words: placed ? "our proposal: not confirmed" : "not placed: place it yourself", tone: "todo" };
}
/** the areas in the order they are listed: the live ones, then those only an older wording names ("kept ready") */
export function areaGroups<T extends ClosedArea>(areas: T[]): { live: T[]; kept: T[] } {
  return { live: areas.filter(drawn), kept: areas.filter((a) => !drawn(a)) };
}
/** one closed area in a line: its name, its size, where — and when it is not live, changed or not placed, that first */
export function closedLine(a: ClosedArea): string {
  const len = a.metres == null ? "" : a.metres >= 1000 ? ` · ${(a.metres / 1000).toFixed(1)} km` : ` · ${a.metres} m`;
  if (a.state === "not live")
    return `${a.name}: not on DFO's live page — ${a.held === "unplaced" ? "not placed yet" : a.kind === "circle" ? `a ${a.radius_m} m circle, kept ready` : "kept ready"} (never bound while it is not live)`;
  const flag = a.state === "changed" ? "CHANGED, check again — " : a.state === "radius" ? "RADIUS DIFFERS — " : "";
  if (a.kind === "circle")
    return `${flag}${a.name}: ${a.ring ? `a ${a.radius_m} m circle at its mouth` : `a ${a.radius_m} m circle, its mouth not placed yet`}`;
  if (a.kind === "line") return `${a.name}: a line across the lake, ${a.line ? "placed by hand" : "not placed"}`;
  const ends = a.ends.length === 2 ? `: ${a.ends.map((e) => `${e.new ? "NEW cut " : ""}${e.label}`).join(" → ")}` : ": not placed yet";
  return `${flag}${a.name}${len}${ends}`;
}

/** THE NEXT WATER WITH WORK LEFT, from anywhere (owner 2026-11-09: "is there a button to go to next river?"): the
 *  first not-done place on another water, in list order after the shown place (wrapping); null when none is left */
export function nextWaterWithWork(queue: CheckPlace[], id: string | null): CheckPlace | null {
  const i = queue.findIndex((p) => p.id === id);
  const key = i >= 0 ? queue[i].water_key : null;
  const round = i >= 0 ? [...queue.slice(i + 1), ...queue.slice(0, i)] : queue;
  return round.find((p) => p.water_key !== key && !isDone(p)) ?? null;
}
/** how many of a water's places are still not done */
export function waterLeft(queue: CheckPlace[], waterKey: string | null): { total: number; left: number } {
  const mine = queue.filter((p) => p.water_key === waterKey);
  return { total: mine.length, left: mine.filter((p) => !isDone(p)).length };
}

/** ONE RULE FOR A GROUP'S OTHER WORDINGS (owner 2026-11-09: "i cant accept it ?"): each wording is done by ITS OWN
 *  state (saved, verified earlier, checked) — a place done by his save never asks for ticks; the wordings that
 *  still need him are named, each to be opened and settled on its own row */
export function groupStillNeeds(members: DfoGroupMember[]): DfoGroupMember[] {
  return members.filter((m) => !m.this && !(m.check && isDone({ check: m.check })));
}

/** AFTER A SAVE OR A CONFIRM, GO ON BY ITSELF (owner 2026-11-09: "it should go to next on that river if there is any
 *  left"): the next NOT-done place on the same water, in list order from the one saved (wrapping); when the water has
 *  none left, the first not-done place of the next water with work (`nextWater`), and the water's count. */
export function nextAfterSave(queue: CheckPlace[], id: string):
    { next: string } | { next: null; water: string; total: number; nextWater: CheckPlace | null } {
  const i = queue.findIndex((p) => p.id === id);
  if (i < 0) return { next: null, water: "", total: 0, nextWater: null };
  const key = queue[i].water_key;
  const round = [...queue.slice(i + 1), ...queue.slice(0, i)];
  const here = round.find((p) => p.water_key === key && !isDone(p));
  if (here) return { next: here.id };
  return { next: null, water: queue[i].water, total: queue.filter((p) => p.water_key === key).length,
           nextWater: round.find((p) => p.water_key !== key && !isDone(p)) ?? null };
}

export interface WaterGroup { same: string; places: WaterPlace[]; why: string[] }
/** the list grouped: places the data calls the same place sit under one heading, in the order the first one comes */
export function waterGroups(places: WaterPlace[]): WaterGroup[] {
  const by = new Map<string, WaterGroup>();
  for (const p of places) {
    const g = by.get(p.same) ?? { same: p.same, places: [], why: [] };
    g.places.push(p);
    for (const w of p.why) if (!g.why.includes(w)) g.why.push(w);
    by.set(p.same, g);
  }
  return [...by.values()];
}
/** a group's heading ("" for a lone place) */
export function groupHeading(g: WaterGroup): string {
  if (g.places.length < 2) return "";
  return g.places[0].source === "regs" ? `These ${g.places.length} rules have the same extent`
    : `These ${g.places.length} wordings are the same place`;
}

/** "SAME PLACE AS…" (a place with no extent takes another's, in the editor): the DFO places on the water that HAVE an
 *  extent, one per distinct extent — the one DFO lists this place as a rewording of first, then its own group */
export function sameAsOptions(places: WaterPlace[], id: string): WaterPlace[] {
  const me = places.find((p) => p.id === id);
  const seen = new Set<string>();
  const rank = (p: WaterPlace) => (me && (me.duplicate_of === p.id || p.duplicate_of === id) ? 0 : me && p.same === me.same ? 1 : 2);
  return places.filter((p) => p.source === "dfo" && p.id !== id && p.extents.length > 0)
    .map((p, i) => ({ p, i })).sort((a, b) => rank(a.p) - rank(b.p) || a.i - b.i).map((x) => x.p)
    .filter((p) => (seen.has(p.extent_key) ? false : (seen.add(p.extent_key), true)));
}

/** SAVE AN EXTENT FOR EVERY WORDING OF THE PLACE (owner 2026-11-09: "saving one extent in the group didnt handle the
 *  reworded version too"): the group part of the save with every other wording that CAN take it, and the ones that
 *  cannot, named with why. Saving for all is his confirming the grouping; a wording taken out of the group is not a
 *  member, so it is never covered. */
export function saveForAll(target: string, members: DfoGroupMember[], fix: boolean):
    { group: GroupSave; covered: DfoGroupMember[]; left: { m: DfoGroupMember; why: string }[] } {
  const all = tickAll(members, fix, false);
  const others = members.filter((m) => !m.this);
  return { group: groupSave(target, members, all, fix, false), covered: others.filter((m) => all.has(m.id)),
           left: others.filter((m) => !all.has(m.id)).map((m) => ({ m, why: untickable(m, fix, false) })) };
}
/** the save line's part about the other wordings ("" when none was covered) */
export function coveredWords(covered: { text: string }[]): string {
  if (!covered.length) return "";
  return `, and the same extent given to ${covered.length} other wording${covered.length > 1 ? "s" : ""} of this place: `
    + covered.map((m) => `“${(m.text || "(the whole water)").slice(0, 70)}”`).join(", ");
}

/** "THESE N WORDINGS ARE THE SAME PLACE": every older wording that can be ticked, ticked (the fast way to the same
 *  ticks; one that cannot be ticked stays out and its reason stays on screen) */
export function tickAll(members: DfoGroupMember[], fix: boolean, checklist: boolean): Set<string> {
  return new Set(members.filter((m) => !m.this && !untickable(m, fix, checklist)).map((m) => m.id));
}

/* THE ONE STATE LINE of a place (owner 2026-11-09: "need to know when it saves"): exactly one of six, colour-coded. A
   mark holds its date, not a time, so "Saved" says the date. */
export type PlaceTone = "none" | "draft" | "wait" | "saved" | "confirmed" | "bad";
export function placeState(a: { editing: boolean; check: PlaceCheck["check"]; checkedDate?: string | null;
                                earlierDate?: string | null; saved?: { state: string; date: string } | null;
                                /** the mark in force is his confirm-as-it-is from the inline editor (`CONFIRMED_AS_IS`) */
                                confirmedAsIs?: boolean;
                                hasExtent: boolean }): { tone: PlaceTone; text: string } {
  if (a.editing) return { tone: "draft", text: "You are previewing a draft: not saved" };
  // his own extent save (`pc.saved`): done while the place holds it; not applied is a fault, said in red
  if (a.check === "unapplied" && a.saved) return { tone: "bad", text: savedWords(a.saved) };
  if (a.check === "saved" && a.saved) return { tone: a.saved.state === "applying" ? "wait" : "confirmed", text: savedWords(a.saved) };
  if (a.check === "stale") return { tone: "wait", text: "Changed since it was saved or checked: check it again" };
  if (a.check === "checked" && a.checkedDate) return { tone: "confirmed", text: `Confirmed by you (${a.checkedDate})` };
  if (a.check === "earlier" && a.earlierDate)
    return { tone: "confirmed", text: `${a.confirmedAsIs ? "Confirmed by you" : "Verified earlier"} (${a.earlierDate})` };
  if (a.saved && a.saved.state === "landed" && a.hasExtent) return { tone: "saved", text: "Saved and on the map" };
  return { tone: "none", text: "Nothing saved yet" };
}
