/* THE CHECKLIST SCREEN'S LOGIC (T532), pure — `tests/checklist.test.ts` runs it under node. The rows themselves are
   generated by the server (`review.checklist`); this decides what the owner can save from them and how a save reads. */
import type { CheckPlace, CheckRow, CheckedList, MarkPost, PlaceCheck, RowKind } from "./types";

/** rows still open: not ✓ and not ticked by the owner — "All correct" waits for none */
export function openRows(rows: CheckRow[], ticked: Set<number>): CheckRow[] {
  return rows.filter((r) => r.state !== "ok" && !ticked.has(r.n));
}

/** the hint under the two buttons */
export function hintWords(rows: CheckRow[], ticked: Set<number>): string {
  const left = openRows(rows, ticked).length;
  return left ? `${left} row${left > 1 ? "s" : ""} not matching — tick each one you have checked, or report it.`
    : "Every row matches.";
}

/** the rows as the mark records them */
export function checkedList(pc: PlaceCheck, ticked: Set<number>, wrong: Set<number>): CheckedList {
  return { digest: pc.digest, rows: pc.rows.map((r) => ({ n: r.n, kind: r.kind, state: r.state,
    ...(r.state !== "ok" && ticked.has(r.n) ? { ticked: true } : {}), ...(wrong.has(r.n) ? { wrong: true } : {}) })) };
}

/** the problem a wrong check names (`marks.PROBLEMS` P), from the kinds of the rows picked — the worst first */
const PROBLEM_OF: Record<RowKind, string> = {
  water: "wrong water", from: "split misplaced", to: "split misplaced", also: "split missing", where: "split missing",
  area: "wrong water", tributaries: "tributary walk over-reaches", except: "undrawn part / unresolved place",
  unchecked: "undrawn part / unresolved place",
};
export function problemOf(rows: CheckRow[], wrong: Set<number>): string {
  const kinds = rows.filter((r) => wrong.has(r.n)).map((r) => r.kind);
  const order: RowKind[] = ["water", "where", "also", "from", "to", "except", "tributaries", "area", "unchecked"];
  const k = order.find((x) => kinds.includes(x));
  return k ? PROBLEM_OF[k] : "undrawn part / unresolved place";
}

/** the note a wrong check carries: each picked row in a few words, then the owner's own */
export function wrongNote(rows: CheckRow[], wrong: Set<number>, note: string): string {
  const picked = rows.filter((r) => wrong.has(r.n))
    .map((r) => `row ${r.n} (${r.kind}${r.quote ? ` “${r.quote.slice(0, 80)}”` : ""} — ours: ${r.ours})`);
  return [`wrong: ${picked.join("; ")}`, note.trim()].filter(Boolean).join(" · ");
}

export interface Who { reviewer: string; seconds: number }

/** THE MARK A CHECK MAKES. DFO: never an extent fix (T525 R1 — a change of extent is the editor's save), always the
 *  extent the owner was shown (`extent_before`, R3). A regulation rule: a rule mark. Its one check is P. */
export function checkBody(target: { source: "dfo"; id: string; seen: unknown } | { source: "regs"; entry_id: string;
                                    rule_id: string },
                          pc: PlaceCheck, call: "ok" | "wrong", ticked: Set<number>, wrong: Set<number>,
                          note: string, who: Who): MarkPost {
  const base = target.source === "dfo"
    ? { scope: "dfo" as const, target: target.id, extent_before: target.seen as MarkPost["extent_before"] }
    : { scope: "rule" as const, target: target.entry_id, rule_id: target.rule_id };
  const checklist = checkedList(pc, ticked, call === "wrong" ? wrong : new Set());
  if (call === "ok")
    return { ...base, verdict: "verified", answers: { P: "y" }, reviewer: who.reviewer, seconds: who.seconds,
             note: note.trim(), checklist };
  return { ...base, verdict: "wrong", answers: { P: "n" }, reviewer: who.reviewer, seconds: who.seconds,
           problem: problemOf(pc.rows, wrong), note: wrongNote(pc.rows, wrong, note), checklist };
}

/** the one status line of the check in force: what was saved and when, or why it must be checked again */
export function checkStatus(pc: PlaceCheck): string {
  if (pc.check === "stale") return "Its words or its extent changed since it was checked: check it again.";
  if (!pc.checked || pc.check === "unchecked") return "Not checked yet.";
  if (pc.check === "checked") {
    const t = pc.checked.rows.filter((r) => r.ticked).length;
    return `Checked ${pc.checked.date}: all correct · ${pc.checked.rows.length} rows${t ? `, ${t} ticked by eye` : ""}`;
  }
  const w = pc.checked.rows.filter((r) => r.wrong).map((r) => r.n);
  return `Checked ${pc.checked.date}: wrong — row${w.length > 1 ? "s" : ""} ${w.join(", ")}`;
}

/** THE PLACE'S POSITION: overall in the list, and on its water ("Chilliwack River: 3 of 7") */
export function where(queue: CheckPlace[], id: string | null): { pos: number; total: number; water: string;
                                                                   onWater: number; ofWater: number } {
  const i = queue.findIndex((p) => p.id === id);
  const k = i >= 0 ? queue[i].water_key : null;
  const mine = queue.filter((p) => p.water_key === k);
  return { pos: i + 1, total: queue.length, water: i >= 0 ? queue[i].water : "",
           onWater: mine.findIndex((p) => p.id === id) + 1, ofWater: mine.length };
}

/** the next / previous place: the queue is grouped by water, so stepping finishes a water before the next */
export function step(queue: CheckPlace[], id: string | null, dir: 1 | -1): string | null {
  const i = queue.findIndex((p) => p.id === id);
  if (i < 0) return queue.length ? queue[0].id : null;
  const j = i + dir;
  return j >= 0 && j < queue.length ? queue[j].id : null;
}

/** the numbered pins: one per row with a point; `on` is the row hovered or picked */
export function pinsFc(rows: CheckRow[], on: number | null): GeoJSON.FeatureCollection {
  const seen = new Map<string, number>();
  return { type: "FeatureCollection", features: rows.filter((r) => r.anchor.coord).map((r) => {
    const [x, y] = r.anchor.coord!;
    const k = `${x},${y}`;
    const i = seen.get(k) ?? 0;          // rows on one point (a water and its tributary call) sit side by side
    seen.set(k, i + 1);
    return { type: "Feature" as const, geometry: { type: "Point" as const, coordinates: [x + i * 0.004, y] },
             properties: { n: String(r.n), state: r.state, on: r.n === on } };
  }) };
}
