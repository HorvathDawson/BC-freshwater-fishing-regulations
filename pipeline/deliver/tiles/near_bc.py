"""(T864) "Near B.C." for the app's location checks, as one small TypeScript constant.

    python -m pipeline.deliver.tiles.near_bc

The app must know, cheaply and offline, whether the device is somewhere its map and regulations can help: in British
Columbia, or close enough that a border town (Jasper, Bellingham, Watson Lake) still works as before. A bare bounding
box lies in both directions (it takes in Calgary and the Alaska panhandle, and the ocean west of Haida Gwaii), and the
mask the map draws (`boundary.py`, 2,308 vertices) is a file the map loads, not something the app holds in memory.

So: the province's outline (the same `bc_boundary.geojson` the mask is cut from) grown by 50 km in BC Albers, then
simplified to 5 km. Growing first fills the fjords and islands into one plain shape, so the result is about 70 points,
and the margin is 45-55 km wherever you stand. The app tests a position against it with one point-in-polygon.
"""

from __future__ import annotations

from pathlib import Path

from pipeline.common.curated import REPO_ROOT, SOURCE

MARGIN_M = 50_000
SIMPLIFY_M = 5_000
OUT = REPO_ROOT / "app" / "packages" / "core" / "src" / "nearBcOutline.ts"


def build(boundary: Path, out: Path = OUT) -> Path:
    import geopandas as gpd

    bc = gpd.read_file(boundary).to_crs(3005).geometry.union_all()
    grown = bc.buffer(MARGIN_M, resolution=4).simplify(SIMPLIFY_M)
    shape = gpd.GeoSeries([grown], crs=3005).to_crs(4326).iloc[0]
    if shape.geom_type != "Polygon" or len(shape.interiors):
        raise SystemExit(f"expected one plain polygon, got {shape.geom_type} with {len(getattr(shape, 'interiors', []))} holes")
    ring = [(round(x, 3), round(y, 3)) for x, y in shape.exterior.coords]
    pairs = ",\n  ".join(", ".join(f"[{x}, {y}]" for x, y in ring[i:i + 6]) for i in range(0, len(ring), 6))
    out.write_text(
        "/**\n"
        f" * GENERATED by `python -m pipeline.deliver.tiles.near_bc` from {boundary.name} — do not edit by hand.\n"
        f" * British Columbia grown by {MARGIN_M // 1000} km, simplified to {SIMPLIFY_M // 1000} km: one ring of "
        f"{len(ring)} [lon, lat] points (closed). See `nearBc.ts`.\n"
        " */\n"
        f"export const NEAR_BC_MARGIN_KM = {MARGIN_M // 1000};\n\n"
        "export const NEAR_BC_RING: readonly (readonly [number, number])[] = [\n"
        f"  {pairs},\n"
        "];\n")
    print(f"  ✅ {out}  {len(ring)} points")
    return out


if __name__ == "__main__":
    build(SOURCE / "bc_boundary.geojson")
