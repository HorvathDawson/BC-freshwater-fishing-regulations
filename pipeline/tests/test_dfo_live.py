def test_queue_puts_the_held_places_in_the_dfo_mode_queue(tmp_path, monkeypatch):
    """Part 4 → DFO mode: `queue` seeds the held places into (a copy of) the entry files — where the review app's DFO
    mode lists every location — and the next feed run joins them: nothing held, nothing told."""
    import shutil
    from pipeline.regs.dfo_salmon import entries as E
    from pipeline.regs.dfo_salmon.parse import parse_region
    from pipeline.regs.dfo_salmon.untangle import untangle
    entries = tmp_path / "entries"
    shutil.copytree(E.ENTRIES_DIR, entries)
    cache = tmp_path / "cache"
    (cache / "raw").mkdir(parents=True)
    for p in FIX.glob("region*-eng.html"):
        shutil.copy(p, cache / "raw" / p.name)
    (cache / "raw" / "region6-eng.html").write_text(_unseen(), encoding="utf-8")
    monkeypatch.setattr(E, "_untangled", lambda slug, _out: untangle(parse_region(
        (cache / "raw" / f"region{slug}-eng.html").read_text(encoding="utf-8"), slug)))
    out = tmp_path / "feed"
    first = L.run(out, fetcher=L.cached_fetcher(cache), entries_dir=entries, now=AT, notify_url="http://n",
                  sender=Sender())
    assert len(first["unplaced"]) == 2
    assert L.queue(out, cache_dir=cache, scrape_dir=tmp_path / "scrape", entries_dir=entries) == ["6"]
    known = E.load("6", entries).by_fingerprint()
    assert all(u["fingerprint"] in known for u in first["unplaced"])
    s = Sender()
    after = L.run(out, fetcher=L.cached_fetcher(cache), entries_dir=entries, now=AT, notify_url="http://n", sender=s)
    assert after["unplaced"] == [] and s.sent == []
    # the real entry files were not touched
    assert not any(u["fingerprint"] in E.load("6").by_fingerprint() for u in first["unplaced"])


