"""T211 parts 2 + 4: THE LIVE DFO FEED (`pipeline/regs/dfo_salmon/live.py`) — no network, no atlas.

  * the feed's per-location answers, composed narrowest first, ARE the release's chain calendar (`compose` ==
    `deliver.salmon.chain_calendar`), so the app re-composing a release chain from the feed decides nothing new;
  * a run over today's pages (the fixtures) joins every location, holds nothing;
  * THE TEST FEED WITH AN UNSEEN LOCATION (part 4): a reworded scope (drift) and an invented water (new_water) are held
    in unplaced.json with their rules, the owner told once each, every other location publishes — and the next run
    tells nobody again;
  * a failed fetch keeps the last answers (stale), two in a row notify; a page that does not parse holds the region;
  * the golden the app's `withSalmonFeed` test reads is current.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from pipeline.deliver import salmon as S
from pipeline.regs.dfo_salmon import live as L
from pipeline.tests.test_salmon_file import BAND, CHAIN, REGION, WATER, _fixture

FIX = Path(__file__).parent / "fixtures" / "dfo_salmon"
GOLDEN = Path(__file__).resolve().parents[2] / "app/packages/core/src/salmonFeed.golden.ts"
GOLDEN_HEAD = ("// GENERATED by pipeline/tests/test_dfo_live.py `golden()` — the app's withSalmonFeed test input. Do not edit.\n"
               "export const SALMON_FEED_GOLDEN = ")


def golden_text() -> str:
    return GOLDEN_HEAD + json.dumps(golden(), indent=1) + ";\n"
AT = "2026-10-27T18:00:00Z"


class Sender:
    def __init__(self):
        self.sent: list[str] = []

    def __call__(self, url, text):
        self.sent.append(text)


def _pages(over: dict | None = None):
    def get(slug):
        if over and slug in over:
            v = over[slug]
            if isinstance(v, Exception):
                raise v
            return v, AT
        return (FIX / f"region{slug}-eng.html").read_text(encoding="utf-8"), AT
    return get


def _cals(rules_by_lid: dict):
    v, g = S._Interner(), S._Interner()
    v(S.NOT_LISTED)
    return {lid: {"r": "6", **L.location_calendar(rs, v, g)} for lid, rs in rules_by_lid.items()}, v.items, g.items


def test_the_feed_composed_narrowest_first_is_the_release_chain():
    locs, verdicts, gears = _cals({"w": WATER, "b": BAND, "a": REGION})
    got = L.compose(["w", "b", "a"], locs, verdicts)
    v, g = S._Interner(), S._Interner()
    v(S.NOT_LISTED)
    want = S.chain_calendar(CHAIN, v, g)
    # the same answers, each through its own table
    for k in range(len(S.SPECIES)):
        assert [verdicts[x] for x in got["sp"][k][1::2]] == [v.items[x] for x in want["sp"][k][1::2]]
        assert got["sp"][k][0::2] == want["sp"][k][0::2]
    assert got["m"] == want["m"]
    assert [gears[x] if x >= 0 else None for x in got["g"][1::2]] == \
        [g.items[x] if x >= 0 else None for x in want["g"][1::2]]
    # a location the feed does not list today says nothing; a chain of nothing is closed every day
    assert L.compose(["gone"], locs, verdicts)["m"] == [0, S.MAP_CODES.index("closed")]


def test_todays_pages_join_every_location(tmp_path):
    got = L.run(tmp_path, fetcher=_pages(), now=AT, notify_url="http://n", sender=Sender())
    ix = got["index"]
    assert ix["format"] == "dfo-feed/1" and ix["unplaced"] == 0 and not got["notices"]
    assert len(ix["locs"]) == 247
    assert ix["verdicts"][0] == S.NOT_LISTED
    assert ix["regions"]["6"]["asof"] == "2026-08-28" and ix["regions"]["6"]["checked"] == AT
    assert not any(r["stale"] or r["held"] for r in ix["regions"].values())
    assert json.loads((tmp_path / "index.json").read_text()) == ix
    assert (tmp_path / "index.json").stat().st_size < 80_000


def _unseen() -> str:
    html = (FIX / "region6-eng.html").read_text(encoding="utf-8")
    html = html.replace("<td>upstream of Highway #16 bridge</td>", "<td>upstream of the Highway 16 crossing</td>", 1)
    row = ("<tr><td>Invented Creek</td><td>all waters</td><td>Coho</td><td>Sep 1 to Oct 31</td>"
           "<td>2 per day</td></tr>\n")
    i = html.index('<th id="c"')
    i = html.rindex("<tr>", 0, i)
    return html[:i] + row + html[i:]


def test_an_unseen_location_is_held_and_told_once(tmp_path):
    base = L.run(tmp_path / "a", fetcher=_pages(), now=AT, notify_url="http://n", sender=Sender())["index"]
    s = Sender()
    got = L.run(tmp_path / "b", fetcher=_pages({"6": _unseen()}), now=AT, notify_url="http://n", sender=s)
    kinds = sorted(u["kind"] for u in got["unplaced"])
    assert kinds == ["drift", "new_water"]
    held = json.loads((tmp_path / "b" / "unplaced.json").read_text())
    assert {u["kind"] for u in held} == {"drift", "new_water"} and all(u["rules"] for u in held)
    assert any("Invented Creek" in t and "rule" in t for t in s.sent)
    assert any("new wording" in t and "likely 6:" in t for t in s.sent)
    assert len(s.sent) == 2
    # every other location publishes, with today's answers
    ix = got["index"]
    reworded = {c["location_id"] for u in got["unplaced"] for c in u["candidates"][:1]}
    assert set(base["locs"]) - set(ix["locs"]) <= reworded
    assert len(ix["locs"]) >= len(base["locs"]) - 1
    # the next run tells nobody again, and keeps when it was first seen
    s2 = Sender()
    again = L.run(tmp_path / "b", fetcher=_pages({"6": _unseen()}), now="2026-10-28T00:00:00Z",
                  notify_url="http://n", sender=s2)
    assert s2.sent == [] and {u["first_seen"] for u in again["unplaced"]} == {AT}


def test_a_failed_fetch_keeps_the_last_answers_and_two_notify(tmp_path):
    L.run(tmp_path, fetcher=_pages(), now=AT, notify_url="http://n", sender=Sender())
    s = Sender()
    one = L.run(tmp_path, fetcher=_pages({"6": OSError("down")}), now=AT, notify_url="http://n", sender=s)
    r6 = one["index"]["regions"]["6"]
    assert r6["stale"] and r6["failures"] == 1 and r6["asof"] == "2026-08-28" and s.sent == []
    assert sum(1 for c in one["index"]["locs"].values() if c["r"] == "6") == 137
    two = L.run(tmp_path, fetcher=_pages({"6": OSError("down")}), now=AT, notify_url="http://n", sender=s)
    assert two["index"]["regions"]["6"]["failures"] == 2 and len(s.sent) == 1 and "Region 6" in s.sent[0]


def test_a_page_that_does_not_parse_holds_the_region(tmp_path):
    L.run(tmp_path, fetcher=_pages(), now=AT, notify_url="http://n", sender=Sender())
    s = Sender()
    got = L.run(tmp_path, fetcher=_pages({"6": "<html>nothing</html>"}), now=AT, notify_url="http://n", sender=s)
    assert got["index"]["regions"]["6"]["held"]
    assert sum(1 for c in got["index"]["locs"].values() if c["r"] == "6") == 137
    assert len(s.sent) == 1


def golden() -> dict:
    """The app's test input: a release built from `test_salmon_file`'s fixture, a feed where the Kispiox's coho window
    moved, and the chains the app must compose from them."""
    # PARTIAL COVERAGE: the resort (not drawn) is on the Kispiox; say its item holds sid 11 (placed) and 14 (not)
    # THE REGION HEADER (owner 2026-10-28): the release's notes from `test_dfo_header`'s page, the Kispiox bound to its
    # item (gnis:4674) and one item upstream of it (gnis:9); the feed's header has the daily limit changed — the feed wins
    from types import SimpleNamespace
    from pipeline.regs.dfo_salmon import header as H
    from pipeline.tests.test_dfo_header import HEADER
    files, feeds, placed, sid_of = _fixture()
    files["6"].waters = [SimpleNamespace(name="Kispiox River", aliases=[], item_ids=["gnis:4674"])]
    payload, sections = S.build(files, feeds, placed, sid_of, {"gnis:4674": [11, 14]},
                                headers={"6": H.parse_header(HEADER, "6")},
                                upstream=lambda items: ["gnis:9"] if "gnis:4674" in items else [])
    feed_notes = H.parse_header(HEADER.replace("is 4. Individual", "is 2. Individual"), "6")
    moved = [dict(WATER[0], when={"dates": [{"from_month": 8, "from_day": 1, "to_month": 9, "to_day": 15}]})] + WATER[1:]
    locs, verdicts, gears = _cals({"6:a": REGION, "6:b(i)": BAND, "6:kispiox": moved, "6:resort": BAND})
    feed = {"format": L.FORMAT, "at": AT, "verdicts": verdicts, "gears": gears, "locs": locs, "unplaced": 0,
            "regions": {"6": {"name": "Skeena", "url": S.PAGE_URL.format(slug="6"), "asof": "2026-10-20",
                              "sha256": "x", "changed": AT, "checked": AT, "stale": False, "held": None,
                              "failures": 0, "notes": feed_notes, "header": H.digest(feed_notes)[:16]}}}
    expect = [L.compose(c["l"], locs, verdicts, c.get("u", ())) for c in payload["chains"]]
    # which header notes a page shows (the app's `salmonNotes`): the feed's notes over the release's scopes
    merged = {**payload, "regions": {**payload["regions"], "6": {**payload["regions"]["6"], "notes": feed_notes}}}
    notes = [{"regions": rs, "item": item, "day": day, "expect": S.notes_for(merged, rs, item, day)}
             for rs, item, day in ((["6"], "gnis:4674", 274), (["6"], "gnis:4674", 182), (["6"], "gnis:9", 274),
                                   (["6"], None, 274), (["6"], "gnis:5", 1), ([], "gnis:4674", 274))]
    return {"release": payload, "sections": sections, "feed": feed, "expect": expect, "notes": notes}


