class Sender:
    def __init__(self):
        self.sent: list[str] = []

    def __call__(self, url, text):
        self.sent.append(text)


def _pages(over: dict | None = None):
    def get(slug):
        if over and slug in over:
            v = over[slug]
            if isinstance(v, Exception):
                raise v
            return v, AT
        return (FIX / f"region{slug}-eng.html").read_text(encoding="utf-8"), AT
    return get


def _cals(rules_by_lid: dict):
    v, g = S._Interner(), S._Interner()
    v(S.NOT_LISTED)
    return {lid: {"r": "6", **L.location_calendar(rs, v, g)} for lid, rs in rules_by_lid.items()}, v.items, g.items


def test_the_feed_composed_narrowest_first_is_the_release_chain():
    locs, verdicts, gears = _cals({"w": WATER, "b": BAND, "a": REGION})
    got = L.compose(["w", "b", "a"], locs, verdicts)
    v, g = S._Interner(), S._Interner()
    v(S.NOT_LISTED)
    want = S.chain_calendar(CHAIN, v, g)
    # the same answers, each through its own table
    for k in range(len(S.SPECIES)):
        assert [verdicts[x] for x in got["sp"][k][1::2]] == [v.items[x] for x in want["sp"][k][1::2]]
        assert got["sp"][k][0::2] == want["sp"][k][0::2]
    assert got["m"] == want["m"]
    assert [gears[x] if x >= 0 else None for x in got["g"][1::2]] == \
        [g.items[x] if x >= 0 else None for x in want["g"][1::2]]
    # a location the feed does not list today says nothing; a chain of nothing is closed every day
    assert L.compose(["gone"], locs, verdicts)["m"] == [0, S.MAP_CODES.index("closed")]


