def _place(loc, kind, section, water=None, area=None):
    """A place as the curated file holds it: its kind and DFO section (the cascade level the card names)."""
    loc.kind, loc.section = kind, section
    if kind.endswith("_default"):
        loc.water = ""                                          # a region / section / area default names no water
    if water:
        loc.water, loc.source_text = water, {"specific_area": area}
    return loc


def _world():
    """h67: a genuine straddler (Region 6 and 7A) — 6 E opens chinook, the Region 7 default closes it and opens summer
    coho; h70: 7A only, the Sustut (a Region 6 named water) over the Region 7 default — one cascade naming two
    regions. `6:late`: curated, not placed — `off`, on the Sustut's water."""
    sustut = SimpleNamespace(water_id="6:sustut-river", item_ids=["gnis:S"])
    locs = [_place(_loc("6:e", 6, 1, [R6E]), "section_default", "E"),
            _place(_loc("7:default", 7, -1, R7), "area_default", None),
            _place(_loc("6:sustut", 6, 3, [{"op": "whole"}]), "water", "B(i)", "Sustut River", "mainstem"),
            _place(_loc("6:late", 6, 3, water_id="6:sustut-river"), "water", "B(i)", "Sustut River", "below the falls")]
    rules = {"6:e": OPEN + GEAR, "7:default": SHUT + COHO_SUMMER, "6:sustut": OPEN, "6:late": OPEN}
    placed = [{"location_id": "6:e", "mapped": True, "sections": ["h60", "h67"]},
              {"location_id": "7:default", "mapped": True, "sections": ["h67", "h70"]},
              {"location_id": "6:sustut", "mapped": True, "sections": ["h70"]}]
    reg = S.section_regions_of(_registry({"6": ["h60", "h67"], "7a": ["h67", "h70"]}), SID)
    return locs, rules, placed, reg, [sustut]


def _who(payload, chain, sp, day):
    a = chain["a"][S.SPECIES.index(sp)]
    v = next(a[k + 1] for k in range(len(a) - 2, -1, -2) if a[k] <= day)
    return chain["l"][v] if v >= 0 else v


def test_a_two_region_chain_names_the_region_whose_answer_shows():
    locs, rules, placed, reg, waters = _world()
    payload, secs = _build(locs, rules, placed, reg, None, waters)
    c67, c70 = _chain_of(payload, secs, 67), _chain_of(payload, secs, 70)
    assert c67["s"] == [[0], [1]]
    # chinook: Region 7 closes it (stricter than E's opening); coho: Region 7's summer opening is not stricter than
    # Region 6 saying nothing (closed), so Region 6 — silent, closed to it — answers all year
    assert [_who(payload, c67, "CH", d) for d in (0, 200)] == ["7:default", "7:default"]
    assert [_who(payload, c67, "CO", d) for d in (0, 200)] == ["6:e", "6:e"]
    # one cascade naming two regions: the Sustut (Region 6) answers chinook; nobody answers coho in winter (-1)
    assert "s" not in c70 and _who(payload, c70, "CH", 0) == "6:sustut"
    assert [_who(payload, c70, "CO", d) for d in (0, 200)] == [NONE, "7:default"]
    # a one-region chain too (the Skeena's cascade): its one place answers chinook all year
    c60 = _chain_of(payload, secs, 60)
    assert c60["r"] == ["6"] and _who(payload, c60, "CH", 0) == "6:e"
    # every place of a chain is named as sourced: region slug, water, DFO section ("B(i)" as printed; none: absent)
    assert payload["p"]["6:e"] == {"r": "6", "sec": "E"}
    assert payload["p"]["6:sustut"] == {"r": "6", "water": "Sustut River", "sec": "B(i)"}
    assert payload["p"]["7:default"] == {"r": "7"}


def test_answering_places_reads_the_composed_answer_never_decides():
    """MUTATION: a composed answer that is neither group's own (a both-words opening) names BOTH (-2), never the first
    group — the region must be the one whose words show."""
    place = [[[0, 1]], [[0, 2]]]                                # one species: place 0 says verdict 1, place 1 verdict 2
    same = lambda c, o: c == (o if o >= 0 else 0)               # noqa: E731
    assert answering_places([[0, 2]], place, [[0], [1]], same, days=3) == [[0, 1]]
    assert answering_places([[0, 1]], place, [[0], [1]], same, days=3) == [[0, 0]]
    assert answering_places([[0, 9]], place, [[0], [1]], same, days=3) == [[0, BOTH]]
    assert answering_places([[0, 0]], [[[0, -1]], None], None, same, days=3) == [[0, NONE]]


