def _box(fr, i=0):
    return fr["table"]["boxes"][i]


def _bands(box):
    return [x["text"] for x in box["bands"]]


def _row(fr, key):
    return next(r for b in fr["table"]["boxes"] for r in b["rows"] if r["key"] == key)


def _proof(fr) -> list:
    """The proof's reading of the table (every text read back; a text G cannot read raises)."""
    return J.Table(fr)


