"""Emit THE FEED FORMATS as TypeScript, so the app and the feeds worker cannot hold another value than the writers.

    python -m pipeline.tools.emit.feed_formats          # write it
    python -m pipeline.tools.emit.feed_formats --check  # fail if it is stale or hand-edited (CI, pnpm check, fast-fail)

The source is `pipeline/common/feed_formats.py` (why it exists is there). Only the strings are shared: what each side
does with a format it does not know stays that side's (the app keeps its last capture and reports; the worker fails
the run).
"""
from __future__ import annotations

import argparse
import json
import sys

from pipeline.common.curated import REPO_ROOT
from pipeline.common.feed_formats import FEEDS

OUT = REPO_ROOT / "app" / "packages" / "core" / "src" / "feedFormats.generated.ts"

_BY = "python -m pipeline.tools.emit.feed_formats"
_SRC = "pipeline/common/feed_formats.py"


def _camel(key: str) -> str:
    head, *rest = key.split("_")
    return head + "".join(w.capitalize() for w in rest)


def render() -> str:
    """The TypeScript, byte for byte."""
    lines = [f"  /** {why} */\n  {_camel(key)}: {json.dumps(fmt)}," for key, (fmt, why) in FEEDS.items()]
    return (f"// GENERATED by `{_BY}`. Do not edit.\n"
            "//\n"
            f"// THE FEED FORMATS ({_SRC}): the format string of every live feed, one source for the\n"
            "// Python writers, the feeds worker and the app (T556). A reader refuses any other; a bump is one edit in the\n"
            "// Python table plus this emit, never a literal typed here or beside a reader.\n\n"
            "export const FEED_FORMATS = {\n" + "\n".join(lines) + "\n} as const;\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale or hand-edited: run `{_BY}` (the source is {_SRC})", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
