"""Emit THE RELEASE CONTRACT (`pipeline/deliver/release/contract.py`) as TypeScript for the app's release reader.

    python -m pipeline.tools.emit.pack          # write app/packages/data/src/pack.generated.ts + core's cell file
    python -m pipeline.tools.emit.pack --check  # fail if either is stale or hand-edited (CI; no data needed)

The regs files' `cell` columns go to a second file, app/packages/core/src/regsCell.generated.ts (`CellIds`; trout
table plan, ticket I0): `@app/core` imports nothing, so it cannot read `pack.generated.ts`, which lives in `@app/data`.

The same pattern as emit_calendar / emit_gauge_policy / answers.model (AGENTS 40): one source, generated copies.
"""
from __future__ import annotations

import argparse
import json
import sys

from pipeline.common.curated import REPO_ROOT
from pipeline.deliver.release import contract as C
from pipeline.deliver.release import manifest as M
from pipeline.deliver.release import slices as S

OUT = REPO_ROOT / "app" / "packages" / "data" / "src" / "pack.generated.ts"
CELL_OUT = REPO_ROOT / "app" / "packages" / "core" / "src" / "regsCell.generated.ts"
#: `cell`'s key columns (answer key, segment); every other column is one answers section's frame id
CELL_KEYS = ("akey", "s")
_BY = "python -m pipeline.tools.emit.pack"


#: the formats of the answer slices (web only: a phone never installs one; the manifest marks each `slice_of`)
_SLICE_FORMATS = frozenset({S.CORE_SLICE_FORMAT, S.WATER_SLICE_FORMAT, S.WATER_SHARED_FORMAT})


def render() -> str:
    files = json.dumps(C.FILES, indent=2, sort_keys=True)
    optional = json.dumps(sorted(C.OPTIONAL))
    optional_sections = json.dumps(C.OPTIONAL_SECTION_TABLES, indent=2, sort_keys=True)
    web_only = json.dumps(sorted(set(C.WEB_ONLY) | {k for k, v in C.FILES.items() if v["format"] in _SLICE_FORMATS}))
    return f'''// GENERATED by `{_BY}` from pipeline/deliver/release/contract.py. Do not edit.
//
// THE RELEASE CONTRACT (P08): every file of data/release/<data_release>/, its format and, for SQLite files, its tables
// and columns. A release whose files differ is refused by the pipeline's own tests; a reader holds to this.

export const MANIFEST_FORMAT = {json.dumps(M.FORMAT)};

/** The nine regulation regions a `regs-<region>` file exists for. */
export const REGIONS = {json.dumps(list(C.REGIONS))} as const;
export type Region = (typeof REGIONS)[number];

export interface PackFile {{
  format: string;
  kind: "sqlite" | "bin";
  tables: Record<string, readonly string[]>;
}}

export const PACK_FILES: Record<string, PackFile> = {files};

/** (T403) The files a release may omit (contract OPTIONAL); every other file is in every published release. */
export const PACK_OPTIONAL: readonly string[] = {optional};

/**
 * (T810 ticket I, trout table contract 2.1) THE OPTIONAL ANSWERS SECTIONS: per section, the `cell` columns and the tables
 * every regs-<region> file carries when the release carries the section (its version in the manifest's
 * `regulations.versions`), and none of them when it does not — all or nothing. The app's reader takes the names from
 * here; the version it was written for stays hand-typed (`OPTIONAL_VERSIONS`, core/src/regs/versions.ts).
 */
export const PACK_OPTIONAL_SECTION_TABLES: Record<string, {{ cell: readonly string[]; tables: Record<string, readonly string[]> }}> = {optional_sections};

/** (T403) The files only the web fetches (the answer slices and contract WEB_ONLY): a phone never installs or holds one. */
export const PACK_WEB_ONLY: readonly string[] = {web_only};

/**
 * (T129) THE WEB REQUEST BUDGET: per moment of a first web visit, the release files it fetches (manifest names;
 * "manifest" is manifest.json, "mask" the tile set's bc_outside.geojson, "regs-{{region}}" the largest region file) and
 * the most they may weigh in bytes as sent. The release step fails over it (`build.gate_problems`); the app's
 * `tools/release-budget.test.ts` holds the live release and the pinned browser walk to it.
 */
export const WEB_BUDGET: Record<string, {{ files: readonly string[]; gate: number }}> = {json.dumps(C.WEB_BUDGET, indent=2)};

/**
 * (T182) The kind handicaps (km) core's `item_near` was cut by — the towns a search row's "near X" can name. Held
 * equal to `@app/core` search.ts's own by a test: the release and the app weigh a town the same way.
 */
export const NEAR_HANDICAP_KM: Record<string, number> = {json.dumps(C.NEAR_HANDICAP_KM, sort_keys=True)};
export const NEAR_HANDICAP_UNKNOWN_KM = {json.dumps(C.NEAR_HANDICAP_UNKNOWN_KM)};

/** Units of the columns the release transforms (the decoders read these). */
export const PACK_UNITS: Record<string, string> = {json.dumps(C.UNITS, indent=2, sort_keys=True)};

/** One file in the manifest (`files.<name>`): the url of its gzip form, raw and gzip bytes, the raw sha256. */
export interface ManifestFile {{
  url: string; bytes: number; gz: number; sha256: string; format: string; section_handles: string;
  /** (T256) An ANSWER SLICE (web only): the whole file it is cut from and its region. A phone never installs one. */
  slice_of?: string; region?: string;
  /** (T369) A file only the web fetches (`lines`: links are web-only). A phone never installs one. */
  web_only?: boolean;
}}
export interface TileRef {{ id?: string; url: string; bytes?: number; sha256?: string }}
/** (T354) pipeline/deliver/release/synopsis.py `append_index`: what an incremental update of the shipped synopsis needs,
 *  so the app appends to a native copy and never reads the book. Refs are [object, generation]; the rest is PDF syntax. */
export interface SynopsisAppend {{
  v: number; startxref: number; size: number; root: [number, number]; info: [number, number] | null;
  id: [string, string] | null;
  /** per page: its ref, its /Annots array's ref, the refs already in that array (PDF syntax, no brackets) */
  page: [number, number, number, number, string][];
}}

/** The sources a release dates (`sources`, pipeline/deliver/release/manifest.py SOURCE_KEYS), in the app's order. */
export const SOURCE_KEYS = {json.dumps(list(M.SOURCE_KEYS))} as const;
export type SourceKey = (typeof SOURCE_KEYS)[number];
/** One source's last update, read from the pipeline's inputs: an ISO day, or null where they record none. */
export interface SourceFact {{ date: string | null; title?: string }}
export interface Manifest {{
  format: typeof MANIFEST_FORMAT;
  data_release: string;
  tiles: {{ compatible: string[]; current: TileRef | null; assets: (TileRef & {{ files_sha256?: string; pin?: string }}) | null;
           mask: TileRef | null }};
  basemap: TileRef | null;
  /** (T215) OUR copy of the synopsis PDF (url relative to the release root, raw bytes); absent on a release built before it.
   *  (T354) `append`: the page index the in-place highlight append needs (absent before it: the book opens the old way). */
  synopsis?: (TileRef & {{ append?: SynopsisAppend | null }}) | null;
  files: Record<string, ManifestFile>;
  regulations: {{ valid_until: string | null; versions: Record<string, number> | null }};
  /** Absent on a release built before it (or a fixture release): every source then reads as not recorded. */
  sources?: Partial<Record<SourceKey, SourceFact>>;
  /** (T251) The oldest app version (semver) that may apply this release; absent: any. An older app keeps the data it has
   *  and says "Update the app to get new regulations" (`@app/core` `releaseAllowed`). */
  minAppVersion?: string | null;
  /** (T251) The ISO day this release was PUBLISHED (stamped by the publish step, never by the deterministic build): the
   *  regs page's "Regulations as of <date>". Absent on an older release: the newest input date stands in. */
  published?: string | null;
}}
'''


def cell_nullable() -> dict:
    """{column: True where it may be NULL} of the regs store's `cell` as the store builder makes it (`schema.sql`, then
    every added section's column: `store.build.added_schema`) — read from SQLite's own table info, never a hand list
    (T810 L: `cell.trout` is NULL where no table is drawn, Q-D3, so its id is `number | null`)."""
    import sqlite3
    from pipeline.deliver.store import build as SB
    con = sqlite3.connect(":memory:")
    try:
        con.executescript(SB.SCHEMA.read_text())
        SB.added_schema(con, SB.ADDED_SECTIONS)
        return {name: not notnull and not pk for _cid, name, _t, notnull, _d, pk in con.execute("PRAGMA table_info(cell)")}
    finally:
        con.close()


def render_cell(nullable: dict | None = None) -> str:
    """`@app/core`'s copy of the regs files' `cell` columns (contract `_REGION_TABLES["cell"]`): `CellIds` was hand-typed
    in core/src/regs/inputs.ts; a column added to `cell` (the trout section's, at the cutover) reaches it by generation.
    A column the store makes nullable (`cell_nullable`) is typed `number | null`, so a NULL is never read as frame 0."""
    cols = list(C._REGION_TABLES["cell"])
    if tuple(cols[:len(CELL_KEYS)]) != CELL_KEYS:
        raise SystemExit(f"{_BY}: contract `cell` no longer starts with {CELL_KEYS}: {cols}")
    secs = cols[len(CELL_KEYS):]
    nullable = cell_nullable() if nullable is None else nullable
    unknown = [c for c in cols if c not in nullable]
    if unknown:
        raise SystemExit(f"{_BY}: contract `cell` columns {unknown} are not in the store's `cell` table")
    ids = "; ".join(f"readonly {c}: number" + (" | null" if nullable[c] else "") for c in secs)
    return f'''// GENERATED by `{_BY}` from pipeline/deliver/release/contract.py (_REGION_TABLES["cell"]). Do not edit.
//
// THE REGS FILES' `cell` TABLE: per answer key and segment, one frame id per answers section. Core imports nothing, so
// the columns are emitted here as well as in @app/data's pack.generated.ts (PACK_FILES). Held by `--check`.

/** Every column of `cell`, in the table's order: the key and segment, then one frame id per section. */
export const CELL_COLUMNS = {json.dumps(cols)} as const;

/** The answers sections a cell names a frame of (`cell` less its key columns). */
export const CELL_SECTIONS = {json.dumps(secs)} as const;
export type CellSection = (typeof CELL_SECTIONS)[number];

/** One cell's frame ids, by section. */
export interface CellIds {{ {ids} }}
'''


def _sync(out, want: str, check: bool) -> int:
    if out.exists() and out.read_text(encoding="utf-8") == want:
        print(f"pack contract up to date: {out.name}")
        return 0
    if check:
        print(f"STALE: {out.relative_to(REPO_ROOT)} — run: {_BY}", file=sys.stderr)
        return 1
    out.write_text(want, encoding="utf-8")
    print(f"wrote {out.relative_to(REPO_ROOT)}")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    return max(_sync(OUT, render(), a.check), _sync(CELL_OUT, render_cell(), a.check))


if __name__ == "__main__":
    raise SystemExit(main())
