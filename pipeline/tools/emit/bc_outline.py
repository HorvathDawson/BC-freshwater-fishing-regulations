"""Emit British Columbia's outline as TypeScript, for the map's label filter (T299).

    python -m pipeline.tools.emit.bc_outline          # write it
    python -m pipeline.tools.emit.bc_outline --check  # fail if it is stale

WHY. The basemap ship stage drops every name outside BC (`basemap_grid.confine_tile`, cut 7), but a phone draws
whatever basemap it holds, and a basemap from before that cut names Seattle, Bellingham and a hundred Washington
hamlets. The web confined the basemap's labels with a `within` filter over the fetched mask (`web/outsideMask.ts`);
the phone had nothing. So the style itself carries the outline (`labels.ts` `inBC`), on both platforms, from the first
frame, whatever archive is underneath.

SMALL ON PURPOSE: the province's own outline (`data/source/bc_boundary.geojson`, the one cut 7 and the mask are
made from), simplified by SIMPLIFY_M and then pushed out by BUFFER_M so a town on the line (White Rock, Osoyoos) is
never cut by the simplification. ~440 vertices, rounded to ~10 m: every basemap label layer's filter repeats it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from pipeline.common.curated import SOURCE

SIMPLIFY_M = 1000
BUFFER_M = 500
OUT = Path(__file__).resolve().parents[3] / "app/packages/map/src/bc-outline.generated.ts"


def outline() -> dict:
    import geopandas as gpd

    g = gpd.read_file(SOURCE / "bc_boundary.geojson").to_crs(3005).geometry.union_all()
    g = g.simplify(SIMPLIFY_M).buffer(BUFFER_M, join_style="mitre")
    g = gpd.GeoSeries([g], crs=3005).to_crs(4326)[0]
    if g.geom_type != "Polygon":
        raise SystemExit(f"bc_outline: expected one polygon, got {g.geom_type}")
    ring = [[round(x, 4), round(y, 4)] for x, y in g.exterior.coords]
    return {"type": "Polygon", "coordinates": [ring]}


def render() -> str:
    o = outline()
    return ("// GENERATED by `python -m pipeline.tools.emit.bc_outline` (T299). Do not edit.\n"
            f"// BC's outline (data/source/bc_boundary.geojson), simplified {SIMPLIFY_M} m, pushed out {BUFFER_M} m: "
            f"{len(o['coordinates'][0])} vertices.\n"
            "export const BC_OUTLINE = " + json.dumps(o, separators=(",", ":")) + " as const;\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m pipeline.tools.emit.bc_outline")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: run python -m pipeline.tools.emit.bc_outline", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}  {len(text) / 1000:.1f} KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
