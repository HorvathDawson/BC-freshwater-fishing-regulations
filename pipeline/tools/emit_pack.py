"""Emit THE RELEASE CONTRACT (`pipeline/deliver/release/contract.py`) as TypeScript for the app's release reader.

    python -m pipeline.tools.emit_pack          # write app/packages/data/src/pack.generated.ts
    python -m pipeline.tools.emit_pack --check  # fail if it is stale or hand-edited (CI; no data needed)

The same pattern as emit_calendar / emit_gauge_policy / answers.model (AGENTS 40): one source, generated copies.
"""
from __future__ import annotations

import argparse
import json
import sys

from pipeline.common.curated import REPO_ROOT
from pipeline.deliver.release import contract as C
from pipeline.deliver.release import manifest as M

OUT = REPO_ROOT / "app" / "packages" / "data" / "src" / "pack.generated.ts"
_BY = "python -m pipeline.tools.emit_pack"


def render() -> str:
    files = json.dumps(C.FILES, indent=2, sort_keys=True)
    return f'''// GENERATED by `{_BY}` from pipeline/deliver/release/contract.py. Do not edit.
//
// THE RELEASE CONTRACT (P08): every file of data/release/<data_release>/, its format and, for SQLite files, its tables
// and columns. A release whose files differ is refused by the pipeline's own tests; a reader holds to this.

export const MANIFEST_FORMAT = {json.dumps(M.FORMAT)};

/** The nine regulation regions a `regs-<region>` file exists for. */
export const REGIONS = {json.dumps(list(C.REGIONS))} as const;
export type Region = (typeof REGIONS)[number];

export interface PackFile {{
  format: string;
  kind: "sqlite" | "bin";
  tables: Record<string, readonly string[]>;
}}

export const PACK_FILES: Record<string, PackFile> = {files};

/** Units of the columns the release transforms (the decoders read these). */
export const PACK_UNITS: Record<string, string> = {json.dumps(C.UNITS, indent=2, sort_keys=True)};

/** One file in the manifest (`files.<name>`): the url of its gzip form, raw and gzip bytes, the raw sha256. */
export interface ManifestFile {{
  url: string; bytes: number; gz: number; sha256: string; format: string; section_handles: string;
}}
export interface TileRef {{ id?: string; url: string; bytes?: number; sha256?: string }}
export interface Manifest {{
  format: typeof MANIFEST_FORMAT;
  data_release: string;
  tiles: {{ compatible: string[]; current: TileRef | null; assets: (TileRef & {{ files_sha256?: string; pin?: string }}) | null;
           mask: TileRef | null }};
  basemap: TileRef | null;
  files: Record<string, ManifestFile>;
  regulations: {{ valid_until: string | null; versions: Record<string, number> | null }};
}}
'''


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    want = render()
    if OUT.exists() and OUT.read_text(encoding="utf-8") == want:
        print(f"pack contract up to date: {OUT.name}")
        return 0
    if a.check:
        print(f"STALE: {OUT.relative_to(REPO_ROOT)} — run: {_BY}", file=sys.stderr)
        return 1
    OUT.write_text(want, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
